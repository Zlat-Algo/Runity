            (title, value) => EditorGUILayout.IntField(title, value));

        Пробел();

        ПолеСДиапазоном("Время до следующего спавна", x => x.времяДоСпавнаМинимальное, x => x.времяДоСпавнаМаксимальное, x => x.времяДоСпавнаСлучайное);

        ПолеСДиапазоном("Время между спавном", x => x.времяМеждуСпавномМинимальное, x => x.времяМеждуСпавномМаксимальное, x => x.времяМеждуСпавномСлучайное);

        //Поле("Уменьшение таймера при спавне", x => x.уменьшениеТаймераПриСпавне,
        //    (title, value) => EditorGUILayout.Slider(title, value, 0, 1));

        Пробел();

        Кнопка("Срочный спавн", component.СрочныйСпавн);
    }
}