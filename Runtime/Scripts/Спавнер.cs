{
    public override void OnInspectorGUI()
    {
        Текст("Этот объект создаёт копии другого объекта. Отрицательное количество даёт бесконечный спавн");
        
        Пробел();

        //component.пауза = GUILayout.Toolbar(component.пауза ? 1 : 0, new GUIContent[] { new GUIContent("кря"), new GUIContent("zhr") }) == 1;
        Поле("Пауза", x => x.пауза,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Пробел();

        Поле("Кого копирует", x => x.когоКопирует,
            (title, value) => (GameObject)EditorGUILayout.ObjectField(title, value, typeof(GameObject), false));

