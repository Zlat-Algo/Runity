#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;
using UnityEngine.Events;
using UnityEngine.Serialization;
using UnityEngine.UI;

/// <summary>
/// Куда идёт время у таймера
/// </summary>
public enum СчётТаймера { ОбратныйОтсчёт, Секундомер }

/// <summary>
/// Как записывается время в тексте
/// </summary>
public enum ФорматВремени { Секунды, МинутыИСекунды, ЧасыМинутыИСекунды }

/// <summary>
/// Отсчитывает время, делает что-то, когда оно истекло, и может показывать его в тексте
/// </summary>
[AddComponentMenu("  Runity/ Работа с объектами/Таймер")]
public class Таймер : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField, FormerlySerializedAs("_таймер")] float _длительность = 10;
    /// <summary>
    /// Сколько секунд отсчитывает таймер
    /// </summary>
    public Дробное длительность { get => _длительность; set => _длительность = value; }

    [SerializeField] СчётТаймера _счёт;
    /// <summary>
    /// Обратный отсчёт показывает, сколько осталось. Секундомер показывает, сколько прошло
    /// </summary>
    public СчётТаймера счёт { get => _счёт; set { _счёт = value; ОбновитьТекст(); } }

    [SerializeField] Флажок _запускатьНаСтарте = да;
    /// <summary>
    /// Если "да", то таймер пойдёт сам при появлении объекта
    /// </summary>
    public Флажок запускатьНаСтарте { get => _запускатьНаСтарте; set => _запускатьНаСтарте = value; }

    [SerializeField] bool _повторять;
    /// <summary>
    /// Если "да", то после срабатывания таймер сразу пойдёт заново
    /// </summary>
    public Флажок повторять { get => _повторять; set => _повторять = value; }

    [SerializeField] Флажок _учитыватьСкоростьВремени = да;
    /// <summary>
    /// Если "да", то таймер замедляется вместе со временем игры и стоит, когда игра на паузе
    /// </summary>
    public Флажок учитыватьСкоростьВремени { get => _учитыватьСкоростьВремени; set => _учитыватьСкоростьВремени = value; }

    [SerializeField] Graphic _текст;
    /// <summary>
    /// В какой текст выводить время. Если не указать, таймер возьмёт текст со своего объекта, если он там есть
    /// </summary>
    public Graphic текст { get => _текст; set { _текст = value; ОбновитьТекст(); } }

    [SerializeField] ФорматВремени _формат = ФорматВремени.МинутыИСекунды;
    /// <summary>
    /// Как записывать время: только секунды (75), минуты и секунды (01:15) или ещё и часы (00:01:15)
    /// </summary>
    public ФорматВремени формат { get => _формат; set { _формат = value; ОбновитьТекст(); } }

    [SerializeField] Флажок _писатьЕдиницы = нет;
    /// <summary>
    /// Если "да", то время пишется с единицами: «1 м. 15 с.» вместо «01:15»
    /// </summary>
    public Флажок писатьЕдиницы { get => _писатьЕдиницы; set { _писатьЕдиницы = value; ОбновитьТекст(); } }

    [SerializeField] Число _знаковПослеЗапятой = 0;
    /// <summary>
    /// Сколько знаков после запятой показывать у секунд: 0 - «15», 1 - «15,3», 2 - «15,27»
    /// </summary>
    public Число знаковПослеЗапятой { get => _знаковПослеЗапятой; set { _знаковПослеЗапятой = Mathf.Clamp(value, 0, 3); ОбновитьТекст(); } }

    [SerializeField] Строка _текстДо = "";
    /// <summary>
    /// Что написать перед временем, например «Осталось: »
    /// </summary>
    public Строка текстДо { get => _текстДо; set { _текстДо = value; ОбновитьТекст(); } }

    [SerializeField] Строка _текстПосле = "";
    /// <summary>
    /// Что написать после времени
    /// </summary>
    public Строка текстПосле { get => _текстПосле; set { _текстПосле = value; ОбновитьТекст(); } }

    [SerializeField] События _приИстечении;
    /// <summary>
    /// Срабатывает, когда время истекло
    /// </summary>
    public События приИстечении => _приИстечении;

    [SerializeField] События _приЗапуске;
    /// <summary>
    /// Срабатывает, когда таймер запустили
    /// </summary>
    public События приЗапуске => _приЗапуске;

    [SerializeField] События _приПаузе;
    /// <summary>
    /// Срабатывает, когда таймер поставили на паузу
    /// </summary>
    public События приПаузе => _приПаузе;

    [SerializeField] События _приКаждойСекунде;
    /// <summary>
    /// Срабатывает каждую целую секунду, пока идёт таймер. Удобно для звука тиканья
    /// </summary>
    public События приКаждойСекунде => _приКаждойСекунде;

    // Действия из старой версии таймера. Новые действия добавляются в «При истечении»
    [SerializeField] UnityEvent _действия;

    [SerializeField] bool _пауза;
    /// <summary>
    /// Пока "да", таймер стоит на месте
    /// </summary>
    public Флажок пауза
    {
        get => _пауза;
        set
        {
            if (_пауза == value) return;
            _пауза = value;
            if (value && Application.isPlaying) _приПаузе.Вызвать();
        }
    }

    /// <summary>
    /// Сколько секунд прошло с запуска
    /// </summary>
    public Дробное прошло { get; private set; }

    /// <summary>
    /// Сколько секунд осталось до срабатывания
    /// </summary>
    public Дробное осталось => Mathf.Max(0, (float)длительность - прошло);

    /// <summary>
    /// Даёт "да", пока таймер идёт, даже если он на паузе
    /// </summary>
    public Флажок идёт { get; private set; }

    /// <summary>
    /// Время в том виде, в котором оно пишется в тексте
    /// </summary>
    public Строка текстВремени => (string)текстДо + Форматировать(счёт == СчётТаймера.ОбратныйОтсчёт ? (float)осталось : (float)прошло) + (string)текстПосле;

    void Start()
    {
        if (текст == null) _текст = ЗаписьТекста.НайтиРядом(this);
        if (запускатьНаСтарте) Запустить();
        else ОбновитьТекст();
    }

    void Update()
    {
        if (!идёт || пауза) return;

        float шаг = учитыватьСкоростьВремени ? Time.deltaTime : Time.unscaledDeltaTime;
        int секундБыло = Mathf.FloorToInt(прошло);
        прошло = (float)прошло + шаг;

        if (Mathf.FloorToInt(прошло) > секундБыло && прошло < длительность) _приКаждойСекунде.Вызвать();

        if (прошло >= длительность) Срабатывание();
        ОбновитьТекст();
    }

    void Срабатывание()
    {
        _приИстечении.Вызвать();
        _действия?.Invoke();

        if (повторять)
        {
            прошло = 0;
        }
        else
        {
            прошло = длительность;
            идёт = нет;
        }
    }

    /// <summary>
    /// Запускает таймер с самого начала
    /// </summary>
    public void Запустить()
    {
        прошло = 0;
        идёт = да;
        _пауза = false;
        _приЗапуске.Вызвать();
        ОбновитьТекст();
    }

    /// <summary>
    /// Запускает таймер заново на другое количество секунд
    /// </summary>
    public void ЗапуститьНа(Дробное секунд)
    {
        длительность = секунд;
        Запустить();
    }

    /// <summary>
    /// Ставит таймер на паузу
    /// </summary>
    public void Приостановить() => пауза = да;

    /// <summary>
    /// Снимает таймер с паузы
    /// </summary>
    public void Продолжить() => пауза = нет;

    /// <summary>
    /// Останавливает таймер. Действия при этом не выполняются
    /// </summary>
    public void Остановить() => идёт = нет;

    /// <summary>
    /// Добавляет секунды к оставшемуся времени. Отрицательное число время отнимает
    /// </summary>
    public void ДобавитьВремя(Дробное секунд)
    {
        прошло = Mathf.Max(0, (float)прошло - секунд);
        ОбновитьТекст();
    }

    /// <summary>
    /// Выполняет действия прямо сейчас, не дожидаясь конца
    /// </summary>
    public void СрочноеСрабатывание() => Срабатывание();

    void ОбновитьТекст()
    {
        if (_текст == null) return;
        ЗаписьТекста.Записать(_текст, текстВремени);
    }

    void OnValidate()
    {
        if (!Application.isPlaying) ОбновитьТекст();
    }

    string Форматировать(float секунд)
    {
        int знаков = Mathf.Clamp(знаковПослеЗапятой, 0, 3);
        long доли = (long)Mathf.Pow(10, знаков);
        // При обратном отсчёте время округляется вверх: «1» видно, пока не наступит ровно ноль
        double точно = (double)секунд * доли;
        long всего = счёт == СчётТаймера.ОбратныйОтсчёт ? (long)System.Math.Ceiling(точно - 0.0001) : (long)System.Math.Floor(точно + 0.0001);
        if (всего < 0) всего = 0;

        long целыхСекунд = всего / доли;
        long дробь = всего % доли;
        string хвост = знаков > 0 ? System.Globalization.CultureInfo.CurrentCulture.NumberFormat.NumberDecimalSeparator + дробь.ToString(new string('0', знаков)) : "";

        long часы = целыхСекунд / 3600, минуты = целыхСекунд / 60 % 60, сек = целыхСекунд % 60;

        switch (формат)
        {
            case ФорматВремени.Секунды:
                return писатьЕдиницы ? $"{целыхСекунд}{хвост} с." : $"{целыхСекунд}{хвост}";

            case ФорматВремени.МинутыИСекунды:
                long всегоМинут = целыхСекунд / 60;
                return писатьЕдиницы ? $"{всегоМинут} м. {сек:00}{хвост} с." : $"{всегоМинут:00}:{сек:00}{хвост}";

            default:
                return писатьЕдиницы ? $"{часы} ч. {минуты:00} м. {сек:00}{хвост} с." : $"{часы:00}:{минуты:00}:{сек:00}{хвост}";
        }
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(Таймер))]
internal class ТаймерEditor : RunityEditor<Таймер>
{
    public override bool RequiresConstantRepaint() => Application.isPlaying;

    protected override void Отрисовать()
    {
        Текст("Этот объект отсчитывает время и делает что-то, когда оно истекло. Время можно показывать в тексте");

        Пробел();

        Поле("Длительность", x => x.длительность, (title, value) => EditorGUILayout.FloatField(title, value));
        Поле("Счёт", x => x.счёт, (title, value) => (СчётТаймера)EditorGUILayout.EnumPopup(title, value));
        Поле("Запускать на старте", x => x.запускатьНаСтарте, (title, value) => EditorGUILayout.Toggle(title, value));
        Поле("Повторять", x => x.повторять, (title, value) => EditorGUILayout.Toggle(title, value));
        Поле("Учитывать скорость времени", x => x.учитыватьСкоростьВремени, (title, value) => EditorGUILayout.Toggle(title, value));
        Поле("Пауза", x => x.пауза, (title, value) => EditorGUILayout.Toggle(title, value));

        Пробел();

        Поле("Текст", x => x.текст, (title, value) => ПолеОбъекта<Graphic>(title, value, true));

        if (компонент.текст != null && !ЗаписьТекста.Подходит(компонент.текст))
        {
            Текст("Сюда нужен текст, а не картинка", MessageType.Warning);
        }

        if (компонент.текст != null || ЗаписьТекста.НайтиРядом(компонент) != null)
        {
            Поле("Формат", x => x.формат, (title, value) => (ФорматВремени)EditorGUILayout.EnumPopup(title, value));
            Поле("Писать единицы", x => x.писатьЕдиницы, (title, value) => EditorGUILayout.Toggle(title, value));
            Поле("Знаков после запятой", x => x.знаковПослеЗапятой, (title, value) => EditorGUILayout.IntSlider(title, value, 0, 3));
            Поле("Текст до", x => x.текстДо, (title, value) => EditorGUILayout.TextField(title, value));
            Поле("Текст после", x => x.текстПосле, (title, value) => EditorGUILayout.TextField(title, value));
            Текст("Будет написано: " + компонент.текстВремени);
        }

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("При истечении", "_приИстечении");
        ОтобразитьСобытие("При запуске", "_приЗапуске");
        ОтобразитьСобытие("При паузе", "_приПаузе");
        ОтобразитьСобытие("При каждой секунде", "_приКаждойСекунде");
        if (компонент.GetType().GetField("_действия", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance).GetValue(компонент) is UnityEvent старые && старые.GetPersistentEventCount() > 0)
        {
            EditorGUILayout.PropertyField(serializedObject.FindProperty("_действия"), new GUIContent("Действия из старой версии"));
        }
        ЗакончитьСобытия();

        if (Application.isPlaying)
        {
            Пробел();

            НачатьГоризонтальнуюГруппу();
            Кнопка("Запустить", x => x.Запустить());
            Кнопка(компонент.пауза ? "Продолжить" : "Пауза", () =>
            {
                foreach (Таймер таймер in components) таймер.пауза = !таймер.пауза;
            });
            Кнопка("Срочное срабатывание", x => x.СрочноеСрабатывание());
            ЗакончитьГоризонтальнуюГруппу();
        }
    }
}
