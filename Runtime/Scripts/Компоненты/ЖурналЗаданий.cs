using System.Collections.Generic;
using System.Linq;
using System.Text;
#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// Хранит взятые задания и их прогресс, засчитывает цели и может показывать список заданий в тексте
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Механики/ Задания/Журнал заданий")]
public class ЖурналЗаданий : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] List<Задание> _сразуВзятые = new List<Задание>();
    /// <summary>
    /// Задания, которые взяты с самого начала игры
    /// </summary>
    public List<Задание> сразуВзятые => _сразуВзятые;

    [SerializeField] Graphic _текст;
    /// <summary>
    /// Текст, в котором показывается список заданий с прогрессом. Можно не указывать
    /// </summary>
    public Graphic текст { get => _текст; set { _текст = value; ОбновитьТекст(); } }

    [SerializeField] Флажок _показыватьВыполненные = нет;
    /// <summary>
    /// Если "да", то выполненные задания тоже видны в тексте, но зачёркнутыми
    /// </summary>
    public Флажок показыватьВыполненные { get => _показыватьВыполненные; set { _показыватьВыполненные = value; ОбновитьТекст(); } }

    [SerializeField] Флажок _сохранять = нет;
    /// <summary>
    /// Если "да", то прогресс заданий сохраняется между запусками игры
    /// </summary>
    public Флажок сохранять { get => _сохранять; set => _сохранять = value; }

    [SerializeField] События _приВзятии;
    /// <summary>
    /// Срабатывает, когда взято новое задание
    /// </summary>
    public События приВзятии => _приВзятии;

    [SerializeField] События _приПрогрессе;
    /// <summary>
    /// Срабатывает, когда засчиталась цель
    /// </summary>
    public События приПрогрессе => _приПрогрессе;

    [SerializeField] События _приВыполнении;
    /// <summary>
    /// Срабатывает, когда задание выполнено целиком
    /// </summary>
    public События приВыполнении => _приВыполнении;

    /// <summary>
    /// Журнал заданий, который появился на сцене первым. Его находят Отметки заданий
    /// </summary>
    public static ЖурналЗаданий главный { get; private set; }

    /// <summary>
    /// Взятые и ещё не выполненные задания
    /// </summary>
    public IReadOnlyList<Задание> активные => взятые.Where(з => !Выполнено(з)).ToList();

    /// <summary>
    /// Задание, которое последним взяли, продвинули или выполнили
    /// </summary>
    public Задание последнее { get; private set; }

    readonly List<Задание> взятые = new List<Задание>();
    readonly Dictionary<Задание, int[]> прогресс = new Dictionary<Задание, int[]>();

    void Awake()
    {
        if (главный == null) главный = this;
    }

    void Start()
    {
        foreach (Задание задание in _сразуВзятые) Взять(задание);
        ОбновитьТекст();
    }

    void OnDestroy()
    {
        if (главный == this) главный = null;
    }

    string Ключ(Задание задание, int цель) => $"Runity.Задание.{задание.name}.{цель}";

    /// <summary>
    /// Даёт задание игроку. Если оно уже взято, ничего не происходит
    /// </summary>
    public void Взять(Задание задание)
    {
        if (задание == null || взятые.Contains(задание)) return;

        int[] счёт = new int[задание.цели.Count];
        if (сохранять)
        {
            for (int i = 0; i < счёт.Length; i++) счёт[i] = PlayerPrefs.GetInt(Ключ(задание, i), 0);
        }

        взятые.Add(задание);
        прогресс[задание] = счёт;
        последнее = задание;
        _приВзятии.Вызвать();
        ОбновитьТекст();
    }

    /// <summary>
    /// Убирает задание из журнала вместе с прогрессом
    /// </summary>
    public void Отказаться(Задание задание)
    {
        if (!взятые.Remove(задание)) return;
        прогресс.Remove(задание);
        if (сохранять) for (int i = 0; i < задание.цели.Count; i++) PlayerPrefs.DeleteKey(Ключ(задание, i));
        ОбновитьТекст();
    }

    /// <summary>
    /// Засчитывает один раз все цели с этой меткой во взятых заданиях
    /// </summary>
    public void Отметить(Строка метка) => Отметить(метка, 1);

    /// <summary>
    /// Засчитывает цели с этой меткой столько раз, сколько указано
    /// </summary>
    public void Отметить(Строка метка, Число сколько)
    {
        if (string.IsNullOrEmpty(метка)) return;

        foreach (Задание задание in взятые.ToList())
        {
            if (Выполнено(задание)) continue;

            int[] счёт = прогресс[задание];
            bool продвинулось = false;
            for (int i = 0; i < задание.цели.Count; i++)
            {
                ЦельЗадания цель = задание.цели[i];
                if (счёт[i] >= цель.сколько) continue;
                if (цель.метка == метка)
                {
                    счёт[i] = Mathf.Min(цель.сколько, счёт[i] + сколько);
                    if (сохранять) PlayerPrefs.SetInt(Ключ(задание, i), счёт[i]);
                    продвинулось = true;
                }
                // По порядку нельзя засчитывать цели дальше первой невыполненной
                if (задание.целиПоПорядку) break;
            }

            if (!продвинулось) continue;

            последнее = задание;
            _приПрогрессе.Вызвать();
            if (Выполнено(задание)) _приВыполнении.Вызвать();
        }
        ОбновитьТекст();
    }

    /// <summary>
    /// Даёт "да", если задание взято
    /// </summary>
    public Флажок Взято(Задание задание) => задание != null && взятые.Contains(задание);

    /// <summary>
    /// Даёт "да", если задание взято и все его цели выполнены
    /// </summary>
    public Флажок Выполнено(Задание задание)
    {
        if (!Взято(задание)) return нет;
        int[] счёт = прогресс[задание];
        for (int i = 0; i < задание.цели.Count; i++) if (счёт[i] < задание.цели[i].сколько) return нет;
        return да;
    }

    /// <summary>
    /// Сколько раз уже засчитана цель с этим номером. Цели считаются с нуля
    /// </summary>
    public Число Прогресс(Задание задание, Число номерЦели)
    {
        if (!Взято(задание) || номерЦели < 0 || номерЦели >= задание.цели.Count) return 0;
        return прогресс[задание][номерЦели];
    }

    /// <summary>
    /// Список заданий с прогрессом в том виде, в котором он пишется в тексте
    /// </summary>
    public Строка ТекстЗаданий()
    {
        StringBuilder строки = new StringBuilder();
        foreach (Задание задание in взятые)
        {
            bool готово = Выполнено(задание);
            if (готово && !показыватьВыполненные) continue;

            строки.AppendLine(готово ? $"<color=#888888>{задание.name} - выполнено</color>" : $"<b>{задание.name}</b>");
            if (готово) continue;

            int[] счёт = прогресс[задание];
            for (int i = 0; i < задание.цели.Count; i++)
            {
                ЦельЗадания цель = задание.цели[i];
                string отметка = счёт[i] >= цель.сколько ? "✓" : "•";
                string число = цель.сколько > 1 ? $" {счёт[i]}/{цель.сколько}" : "";
                строки.AppendLine($"  {отметка} {цель.описание}{число}");
                if (задание.целиПоПорядку && счёт[i] < цель.сколько) break;
            }
        }
        return строки.ToString().TrimEnd();
    }

    void ОбновитьТекст()
    {
        if (_текст == null) return;
        if (_текст is Text обычный) обычный.supportRichText = true;
        ЗаписьТекста.Записать(_текст, ТекстЗаданий());
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(ЖурналЗаданий))]
internal class ЖурналЗаданийEditor : RunityEditor<ЖурналЗаданий>
{
    public override bool RequiresConstantRepaint() => Application.isPlaying;

    protected override void Отрисовать()
    {
        Текст("Этот объект хранит задания игрока. Задания создаются через Create - Runity - Задание, а цели засчитываются методом «Отметить» с меткой цели или Отметкой задания");

        Пробел();

        НачатьСобытия();
        ОтобразитьСвойство("Сразу взятые", "_сразуВзятые");
        ЗакончитьСобытия();

        Поле("Текст", x => x.текст, (title, value) => ПолеОбъекта<Graphic>(title, value, true));
        Поле("Показывать выполненные", x => x.показыватьВыполненные, (title, value) => EditorGUILayout.Toggle(title, value));
        Поле("Сохранять", x => x.сохранять, (title, value) => EditorGUILayout.Toggle(title, value));

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("При взятии", "_приВзятии");
        ОтобразитьСобытие("При прогрессе", "_приПрогрессе");
        ОтобразитьСобытие("При выполнении", "_приВыполнении");
        ЗакончитьСобытия();

        if (Application.isPlaying)
        {
            Пробел();
            string список = компонент.ТекстЗаданий();
            Текст(string.IsNullOrEmpty(список) ? "Заданий нет" : System.Text.RegularExpressions.Regex.Replace(список, "<[^>]+>", ""));
        }
    }
}
#endif
