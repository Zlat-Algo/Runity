using System.Collections.Generic;
#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;

/// <summary>
/// Персонаж, с которым можно поговорить. Запускает свой Диалог в Окне диалога и реагирует на метки из разговора
/// </summary>
[AddComponentMenu("  Runity/ Механики/ Диалоги/Собеседник")]
public class Собеседник : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] Диалог _диалог;
    /// <summary>
    /// Какой разговор начинается
    /// </summary>
    [Обязательное]
    public Диалог диалог { get => _диалог; set => _диалог = value; }

    [SerializeField] ОкноДиалога _окно;
    /// <summary>
    /// В каком окне показывать разговор. Если не указать, возьмётся первое окно диалога на сцене
    /// </summary>
    public ОкноДиалога окно { get => _окно; set => _окно = value; }

    [SerializeField] Флажок _начинатьПриКасании = нет;
    /// <summary>
    /// Если "да", то разговор начнётся сам, когда в зону объекта (триггер) войдёт объект с подходящим тегом
    /// </summary>
    public Флажок начинатьПриКасании { get => _начинатьПриКасании; set => _начинатьПриКасании = value; }

    [SerializeField] Теги _теги = new Теги("Player");
    /// <summary>
    /// Кто может начать разговор касанием
    /// </summary>
    public Теги теги { get => _теги; set => _теги = value; }

    [SerializeField] Флажок _толькоОдинРаз = нет;
    /// <summary>
    /// Если "да", то поговорить можно только один раз
    /// </summary>
    public Флажок толькоОдинРаз { get => _толькоОдинРаз; set => _толькоОдинРаз = value; }

    [SerializeField] List<РеакцияДиалога> _реакции = new List<РеакцияДиалога>();
    /// <summary>
    /// Что делать, когда в разговоре с этим собеседником встречается метка, например «дать_квест»
    /// </summary>
    public List<РеакцияДиалога> реакции => _реакции;

    [SerializeField] События _приНачалеРазговора;
    /// <summary>
    /// Срабатывает, когда начался разговор с этим собеседником
    /// </summary>
    public События приНачалеРазговора => _приНачалеРазговора;

    [SerializeField] События _приКонцеРазговора;
    /// <summary>
    /// Срабатывает, когда разговор с этим собеседником закончился
    /// </summary>
    public События приКонцеРазговора => _приКонцеРазговора;

    /// <summary>
    /// Сколько раз с собеседником уже поговорили
    /// </summary>
    public Число разговоров { get; private set; }

    /// <summary>
    /// Даёт "да", пока идёт разговор именно с этим собеседником
    /// </summary>
    public Флажок говорит { get; private set; }

    /// <summary>
    /// Начинает разговор
    /// </summary>
    public void Поговорить()
    {
        ОкноДиалога окноРазговора = окно != null ? окно : ОкноДиалога.главное;
        if (окноРазговора == null)
        {
            Консоль.НапечататьОшибку("На сцене нет Окна диалога. Создайте его: правый клик в Hierarchy - Runity - Интерфейс - Элементы - Окно диалога", this);
            return;
        }
        if (диалог == null || говорит || окноРазговора.идётРазговор) return;
        if (толькоОдинРаз && разговоров > 0) return;

        говорит = да;
        разговоров = (int)разговоров + 1;
        окноРазговора.ВстретиласьМетка += ПриМетке;
        окноРазговора.РазговорЗакончен += ПриКонце;
        _приНачалеРазговора.Вызвать();
        окноРазговора.Начать(диалог);

        void ПриКонце()
        {
            окноРазговора.ВстретиласьМетка -= ПриМетке;
            окноРазговора.РазговорЗакончен -= ПриКонце;
            говорит = нет;
            _приКонцеРазговора.Вызвать();
        }
    }

    void ПриМетке(string метка)
    {
        foreach (РеакцияДиалога реакция in _реакции)
        {
            if (реакция.метка == метка) реакция.действия.Вызвать();
        }
    }

    void OnTriggerEnter(Collider другой)
    {
        if (начинатьПриКасании && теги.Подходит(другой.gameObject)) Поговорить();
    }

    void OnTriggerEnter2D(Collider2D другой)
    {
        if (начинатьПриКасании && теги.Подходит(другой.gameObject)) Поговорить();
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(Собеседник))]
internal class СобеседникEditor : RunityEditor<Собеседник>
{
    protected override void Отрисовать()
    {
        Текст("С этим объектом можно поговорить. Разговор запускается методом «Поговорить», например из Взаимодействия, или сам при касании");

        Пробел();

        Поле("Диалог", x => x.диалог, (title, value) => ПолеОбъекта<Диалог>(title, value));
        Поле("Окно", x => x.окно, (title, value) => ПолеОбъекта<ОкноДиалога>(title, value, true));
        Поле("Только один раз", x => x.толькоОдинРаз, (title, value) => EditorGUILayout.Toggle(title, value));
        Поле("Начинать при касании", x => x.начинатьПриКасании, (title, value) => EditorGUILayout.Toggle(title, value));
        if (компонент.начинатьПриКасании)
        {
            ОтобразитьТеги("Теги", "_теги");
            if (компонент.GetComponent<Collider>() == null && компонент.GetComponent<Collider2D>() == null)
                Текст("Для касания объекту нужен коллайдер с галочкой «Триггер»", MessageType.Warning);
        }

        Пробел();

        НачатьСобытия();
        ОтобразитьСвойство("Реакции на метки", "_реакции");
        ОтобразитьСобытие("При начале разговора", "_приНачалеРазговора");
        ОтобразитьСобытие("При конце разговора", "_приКонцеРазговора");
        ЗакончитьСобытия();

        if (Application.isPlaying)
        {
            Пробел();
            Кнопка("Поговорить", x => x.Поговорить());
        }
    }
}
#endif
