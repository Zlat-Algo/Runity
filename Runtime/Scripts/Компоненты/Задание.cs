using System;
using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Одна цель задания, например «Собрать 5 яблок»
/// </summary>
[Serializable]
public class ЦельЗадания
{
    [Подсказка("Что нужно сделать. Так цель пишется в списке заданий")]
    public string описание = "Сделать что-нибудь";

    [Подсказка("Слово, по которому засчитывается цель. Его передают Журналу заданий через «Отметить» или Отметку задания")]
    public string метка = "";

    [Минимум(1), Подсказка("Сколько раз нужно отметить цель, чтобы она выполнилась")]
    public int сколько = 1;
}

/// <summary>
/// Задание для игрока: название, описание и цели. Выдаётся и отслеживается Журналом заданий
/// </summary>
[CreateAssetMenu(fileName = "Новое задание", menuName = "Runity/Задание", order = -92)]
public class Задание : ScriptableObject
{
    [SerializeField, МногострочныйТекст(3)] string _описание = "";
    /// <summary>
    /// Что рассказать игроку о задании
    /// </summary>
    public Строка описание { get => _описание; set => _описание = value; }

    [SerializeField] List<ЦельЗадания> _цели = new List<ЦельЗадания> { new ЦельЗадания() };
    /// <summary>
    /// Что нужно сделать. Задание выполнено, когда выполнены все цели
    /// </summary>
    public List<ЦельЗадания> цели => _цели;

    [SerializeField] Флажок _целиПоПорядку = false;
    /// <summary>
    /// Если "да", то цели засчитываются строго по очереди: следующая не считается, пока не выполнена предыдущая
    /// </summary>
    public Флажок целиПоПорядку { get => _целиПоПорядку; set => _целиПоПорядку = value; }

    /// <summary>
    /// Название задания. Это имя файла задания
    /// </summary>
    public Строка название => name;
}
