using System;
using System.Collections.Generic;
#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;

/// <summary>
/// Слово из диалога и что делать, когда оно встретилось
/// </summary>
[Serializable]
public class РеакцияДиалога
{
    [Подсказка("Слово, написанное в поле «Метка» у реплики или ответа")]
    public string метка = "";

    [Подсказка("Что сделать, когда в разговоре встретилась эта метка")]
    public События действия;
}

/// <summary>
/// Окно в интерфейсе, которое показывает разговор: имя, портрет, текст по буквам и кнопки ответов
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Интерфейс/ Элементы/Окно диалога")]
public class ОкноДиалога : RunityComponent, IPointerClickHandler
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] GameObject _панель;
    /// <summary>
    /// Что показывается во время разговора и прячется после него. Если не указать, прячется сам этот объект
    /// </summary>
    public GameObject панель { get => _панель; set => _панель = value; }

    [SerializeField] Graphic _текстИмени;
    /// <summary>
    /// Текст, в котором пишется имя говорящего
    /// </summary>
    public Graphic текстИмени { get => _текстИмени; set => _текстИмени = value; }

    [SerializeField] Graphic _текстРеплики;
    /// <summary>
    /// Текст, в котором пишется реплика
    /// </summary>
    [Обязательное]
    public Graphic текстРеплики { get => _текстРеплики; set => _текстРеплики = value; }

    [SerializeField] Image _портрет;
    /// <summary>
    /// Картинка, в которой показывается портрет говорящего
    /// </summary>
    public Image портрет { get => _портрет; set => _портрет = value; }

    [SerializeField] Button _образецОтвета;
    /// <summary>
    /// Кнопка-образец для ответов. Для каждого ответа создаётся её копия рядом с ней, а сама она прячется
    /// </summary>
    public Button образецОтвета { get => _образецОтвета; set => _образецОтвета = value; }

    [SerializeField] Дробное _буквВСекунду = 40;
    /// <summary>
    /// Сколько букв в секунду появляется. 0 - весь текст сразу
    /// </summary>
    public Дробное буквВСекунду { get => _буквВСекунду; set => _буквВСекунду = value; }

    [SerializeField] Клавиша _клавишаДальше = Клавиша.Пробел;
    /// <summary>
    /// Какой клавишей листать разговор. Ещё можно щёлкнуть по окну
    /// </summary>
    public Клавиша клавишаДальше { get => _клавишаДальше; set => _клавишаДальше = value; }

    [SerializeField] Флажок _останавливатьИгру = нет;
    /// <summary>
    /// Если "да", то на время разговора игра замирает
    /// </summary>
    public Флажок останавливатьИгру { get => _останавливатьИгру; set => _останавливатьИгру = value; }

    [SerializeField] Флажок _освобождатьМышку = да;
    /// <summary>
    /// Если "да", то на время разговора появляется курсор мыши, чтобы можно было нажимать на ответы. Ответ можно выбрать и цифрой на клавиатуре
    /// </summary>
    public Флажок освобождатьМышку { get => _освобождатьМышку; set => _освобождатьМышку = value; }

    [SerializeField] List<РеакцияДиалога> _реакции = new List<РеакцияДиалога>();
    /// <summary>
    /// Что делать, когда в разговоре встречается метка. Работает для всех разговоров в этом окне
    /// </summary>
    public List<РеакцияДиалога> реакции => _реакции;

    [SerializeField] События _приНачале;
    /// <summary>
    /// Срабатывает, когда начался разговор
    /// </summary>
    public События приНачале => _приНачале;

    [SerializeField] События _приРеплике;
    /// <summary>
    /// Срабатывает при показе каждой реплики
    /// </summary>
    public События приРеплике => _приРеплике;

    [SerializeField] События _приОкончании;
    /// <summary>
    /// Срабатывает, когда разговор закончился
    /// </summary>
    public События приОкончании => _приОкончании;

    /// <summary>
    /// Окно диалога, которое появилось на сцене первым. Его находят Собеседники
    /// </summary>
    public static ОкноДиалога главное { get; private set; }

    /// <summary>
    /// Какой разговор идёт сейчас. Пусто, если никакой
    /// </summary>
    public Диалог диалог { get; private set; }

    /// <summary>
    /// Номер реплики, которая показывается сейчас
    /// </summary>
    public Число номерРеплики { get; private set; } = -1;

    /// <summary>
    /// Даёт "да", пока идёт разговор
    /// </summary>
    public Флажок идётРазговор => диалог != null;

    /// <summary>
    /// Даёт "да", пока текст реплики ещё печатается
    /// </summary>
    public Флажок печатается => показаноБукв < полныйТекст.Length;

    /// <summary>
    /// Срабатывает, когда в разговоре встретилась метка. Через него Собеседник узнаёт о своих метках
    /// </summary>
    public event Action<string> ВстретиласьМетка;

    /// <summary>
    /// Срабатывает, когда разговор закончился. Через него Собеседник узнаёт о конце своего разговора
    /// </summary>
    public event Action РазговорЗакончен;

    string полныйТекст = "";
    float показаноБукв;
    float былаСкоростьВремени = 1;
    РежимМышки былаМышка;
    readonly List<Button> кнопки = new List<Button>();
    int кадрНачала;

    GameObject видимое => панель != null ? панель : gameObject;

    void Awake()
    {
        if (главное == null) главное = this;
        if (образецОтвета != null) образецОтвета.gameObject.SetActive(false);
    }

    void Start()
    {
        if (диалог == null && видимое != gameObject) видимое.SetActive(false);
        else if (диалог == null) Показать(false);
    }

    void OnDestroy()
    {
        if (главное == this) главное = null;
    }

    // Если окно прячет само себя, выключать объект нельзя: тогда оно перестанет работать
    void Показать(bool видно)
    {
        if (видимое != gameObject)
        {
            видимое.SetActive(видно);
            return;
        }
        CanvasGroup группа = GetComponent<CanvasGroup>();
        if (группа == null) группа = gameObject.AddComponent<CanvasGroup>();
        группа.alpha = видно ? 1 : 0;
        группа.blocksRaycasts = видно;
        группа.interactable = видно;
    }

    /// <summary>
    /// Начинает разговор с первой реплики
    /// </summary>
    public void Начать(Диалог новыйДиалог)
    {
        if (новыйДиалог == null || новыйДиалог.реплики.Count == 0) return;

        диалог = новыйДиалог;
        кадрНачала = Time.frameCount;
        Показать(true);
        if (останавливатьИгру)
        {
            былаСкоростьВремени = Time.timeScale;
            Time.timeScale = 0;
        }
        if (освобождатьМышку)
        {
            былаМышка = Мышка.режим;
            Мышка.режим = РежимМышки.Свободная;
        }
        _приНачале.Вызвать();
        ПоказатьРеплику(0);
    }

    /// <summary>
    /// Допечатывает текст, а если он уже допечатан - переходит к следующей реплике
    /// </summary>
    public void Дальше()
    {
        if (диалог == null) return;
        if (печатается)
        {
            показаноБукв = полныйТекст.Length;
            Записать();
            return;
        }

        РепликаДиалога реплика = диалог.Реплика(номерРеплики);
        if (реплика == null || реплика.ответы.Count > 0) return;
        ПоказатьРеплику(диалог.Следующая(номерРеплики, реплика.переход, реплика.номерРеплики));
    }

    /// <summary>
    /// Выбирает ответ по номеру. Ответы считаются с нуля
    /// </summary>
    public void Выбрать(Число номерОтвета)
    {
        РепликаДиалога реплика = диалог != null ? диалог.Реплика(номерРеплики) : null;
        if (реплика == null || номерОтвета < 0 || номерОтвета >= реплика.ответы.Count) return;

        ОтветДиалога ответ = реплика.ответы[номерОтвета];
        Метка(ответ.метка);
        if (диалог == null) return;
        ПоказатьРеплику(диалог.Следующая(номерРеплики, ответ.переход, ответ.номерРеплики));
    }

    /// <summary>
    /// Сразу заканчивает разговор
    /// </summary>
    public void Закончить()
    {
        if (диалог == null) return;

        диалог = null;
        номерРеплики = -1;
        УбратьКнопки();
        Показать(false);
        if (останавливатьИгру) Time.timeScale = былаСкоростьВремени;
        if (освобождатьМышку) Мышка.режим = былаМышка;

        _приОкончании.Вызвать();
        РазговорЗакончен?.Invoke();
    }

    void ПоказатьРеплику(Число номер)
    {
        РепликаДиалога реплика = диалог.Реплика(номер);
        if (реплика == null)
        {
            Закончить();
            return;
        }

        номерРеплики = номер;
        полныйТекст = реплика.текст ?? "";
        показаноБукв = буквВСекунду > 0 ? 0 : полныйТекст.Length;
        Записать();

        if (текстИмени != null) ЗаписьТекста.Записать(текстИмени, реплика.говорящий);
        if (портрет != null)
        {
            портрет.sprite = реплика.портрет;
            портрет.enabled = реплика.портрет != null;
        }

        УбратьКнопки();
        if (образецОтвета != null)
        {
            for (int i = 0; i < реплика.ответы.Count; i++)
            {
                int номерОтвета = i;
                Button кнопка = Instantiate(образецОтвета, образецОтвета.transform.parent);
                кнопка.gameObject.SetActive(true);
                кнопка.name = "Ответ " + (i + 1);
                Graphic надпись = кнопка.GetComponentInChildren<Text>() as Graphic ?? кнопка.GetComponentInChildren<TMPro.TMP_Text>();
                if (надпись != null) ЗаписьТекста.Записать(надпись, (i < 9 ? $"{i + 1}. " : "") + реплика.ответы[i].текст);
                кнопка.onClick.AddListener(() => Выбрать(номерОтвета));
                кнопки.Add(кнопка);
            }
        }

        _приРеплике.Вызвать();
        Метка(реплика.метка);
    }

    void Метка(string метка)
    {
        if (string.IsNullOrEmpty(метка)) return;
        foreach (РеакцияДиалога реакция in _реакции)
        {
            if (реакция.метка == метка) реакция.действия.Вызвать();
        }
        ВстретиласьМетка?.Invoke(метка);
    }

    void УбратьКнопки()
    {
        foreach (Button кнопка in кнопки) if (кнопка != null) Destroy(кнопка.gameObject);
        кнопки.Clear();
    }

    void Записать()
    {
        if (текстРеплики != null) ЗаписьТекста.Записать(текстРеплики, полныйТекст.Substring(0, Mathf.Min(полныйТекст.Length, (int)показаноБукв)));
    }

    void Update()
    {
        if (диалог == null) return;

        if (печатается)
        {
            показаноБукв += буквВСекунду * Time.unscaledDeltaTime;
            Записать();
        }

        // В кадре начала разговора нажатие уже потрачено на то, чтобы его начать
        if (Time.frameCount == кадрНачала) return;
        if (Управление.КлавишаНажата(клавишаДальше)) Дальше();

        // Ответы можно выбирать цифрами
        UnityEngine.InputSystem.Keyboard клавиатура = UnityEngine.InputSystem.Keyboard.current;
        if (клавиатура == null || печатается) return;
        for (int i = 0; i < кнопки.Count && i < 9; i++)
        {
            if (клавиатура[UnityEngine.InputSystem.Key.Digit1 + i].wasPressedThisFrame || клавиатура[UnityEngine.InputSystem.Key.Numpad1 + i].wasPressedThisFrame)
            {
                Выбрать(i);
                return;
            }
        }
    }

    /// <summary>
    /// Щелчок по окну листает разговор
    /// </summary>
    public void OnPointerClick(PointerEventData данные) => Дальше();
}

