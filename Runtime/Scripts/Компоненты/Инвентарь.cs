using System;
using System.Collections.Generic;
#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;

/// <summary>
/// Одна ячейка инвентаря: какая вещь в ней лежит и сколько
/// </summary>
[Serializable]
public class ЗаписьИнвентаря
{
    /// <summary>
    /// Какая вещь лежит в ячейке
    /// </summary>
    public Вещь вещь;
    /// <summary>
    /// Название предмета, если он задан без файла Вещи
    /// </summary>
    public string название;
    /// <summary>
    /// Сколько таких предметов лежит в ячейке
    /// </summary>
    public int количество = 1;

    /// <summary>
    /// Название предмета: из Вещи или из поля Название
    /// </summary>
    public string имя => вещь != null ? вещь.name : название;

    /// <summary>
    /// Даёт "да", если в ячейке ничего нет
    /// </summary>
    public bool пуста => количество <= 0 || string.IsNullOrEmpty(имя);

    /// <summary>
    /// Сколько предметов помещается в эту ячейку
    /// </summary>
    public int максимум => вещь != null ? вещь.максимумВЯчейке : int.MaxValue;

    internal void Опустошить()
    {
        вещь = null;
        название = "";
        количество = 0;
    }
}

/// <summary>
/// Хранит вещи по ячейкам. Одинаковые вещи складываются в одну ячейку, пока она не заполнится
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Механики/ Инвентарь/Инвентарь")]
public class Инвентарь : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] List<ЗаписьИнвентаря> _предметы = new List<ЗаписьИнвентаря>();
    /// <summary>
    /// Все ячейки инвентаря по порядку. Пустые ячейки есть, только если количество ячеек ограничено
    /// </summary>
    public IReadOnlyList<ЗаписьИнвентаря> предметы => _предметы;

    [SerializeField] Число _количествоЯчеек = 0;
    /// <summary>
    /// Сколько ячеек в инвентаре. 0 означает, что ячеек сколько угодно
    /// </summary>
    public Число количествоЯчеек
    {
        get => _количествоЯчеек;
        set
        {
            _количествоЯчеек = Mathf.Max(0, value);
            ПодогнатьЯчейки();
            Сообщить();
        }
    }

    [SerializeField] События _приИзменении;
    /// <summary>
    /// Срабатывает, когда вещи добавились, убрались или переместились
    /// </summary>
    public События приИзменении => _приИзменении;

    [SerializeField] События _приДобавлении;
    /// <summary>
    /// Срабатывает, когда в инвентарь что-то положили
    /// </summary>
    public События приДобавлении => _приДобавлении;

    [SerializeField] События _приНехваткеМеста;
    /// <summary>
    /// Срабатывает, когда вещь не поместилась целиком
    /// </summary>
    public События приНехваткеМеста => _приНехваткеМеста;

    /// <summary>
    /// Для кода: вызывается при любом изменении инвентаря. На него подписываются ячейки
    /// </summary>
    public event Action Изменился;

    /// <summary>
    /// Название предмета, который добавили или убрали последним
    /// </summary>
    public Строка последнийПредмет { get; private set; }

    /// <summary>
    /// Вещь, которую добавили или убрали последней
    /// </summary>
    public Вещь последняяВещь { get; private set; }

    /// <summary>
    /// Даёт "да", если все ячейки заняты и полностью заполнены
    /// </summary>
    public Флажок заполнен => количествоЯчеек > 0 && _предметы.TrueForAll(запись => !запись.пуста && запись.количество >= запись.максимум);

    void Awake() => ПодогнатьЯчейки();

    void ПодогнатьЯчейки()
    {
        if (количествоЯчеек <= 0)
        {
            _предметы.RemoveAll(запись => запись == null || запись.пуста);
            return;
        }
        while (_предметы.Count < количествоЯчеек) _предметы.Add(new ЗаписьИнвентаря { количество = 0 });
    }

    void Сообщить()
    {
        _приИзменении.Вызвать();
        Изменился?.Invoke();
    }

    /// <summary>
    /// Даёт содержимое ячейки по номеру, считая с нуля. Если такой ячейки нет, будет пусто
    /// </summary>
    public ЗаписьИнвентаря Ячейка(Число номер) => номер >= 0 && номер < _предметы.Count ? _предметы[номер] : null;

    /// <summary>
    /// Сколько всего таких предметов в инвентаре
    /// </summary>
    public Число Количество(Строка название)
    {
        int всего = 0;
        foreach (ЗаписьИнвентаря запись in _предметы)
        {
            if (!запись.пуста && запись.имя == название) всего += запись.количество;
        }
        return всего;
    }

    /// <summary>
    /// Сколько всего таких вещей в инвентаре
    /// </summary>
    public Число Количество(Вещь вещь) => вещь != null ? Количество(вещь.name) : 0;

    /// <summary>
    /// Даёт "да", если предметов хватает
    /// </summary>
    public Флажок Есть(Строка название, Число сколько) => Количество(название) >= сколько;

    /// <summary>
    /// Даёт "да", если вещей хватает
    /// </summary>
    public Флажок Есть(Вещь вещь, Число сколько) => Количество(вещь) >= сколько;

    /// <summary>
    /// Кладёт предметы по названию. Если есть файл Вещи с таким названием, то берутся его настройки
    /// </summary>
    public Число Добавить(Строка название, Число сколько)
    {
        Вещь вещь = Вещь.Найти(название);
        return Положить(вещь, вещь != null ? (string)вещь.name : (string)название, сколько);
    }

    /// <summary>
    /// Кладёт вещи в инвентарь и даёт, сколько из них не поместилось
    /// </summary>
    public Число Добавить(Вещь вещь, Число сколько)
    {
        if (вещь == null || !вещь.учитывается) return сколько;
        return Положить(вещь, вещь.name, сколько);
    }

    Число Положить(Вещь вещь, string имя, int сколько)
    {
        if (string.IsNullOrEmpty(имя) || сколько <= 0) return 0;

        int осталось = сколько;
        int максимум = вещь != null ? вещь.максимумВЯчейке : int.MaxValue;

        // Сначала дополняем ячейки, где такие вещи уже лежат
        foreach (ЗаписьИнвентаря запись in _предметы)
        {
            if (осталось == 0) break;
            if (запись.пуста || запись.имя != имя) continue;

            int влезет = Mathf.Min(осталось, максимум - запись.количество);
            if (влезет <= 0) continue;
            запись.количество += влезет;
            осталось -= влезет;
        }

        // Потом занимаем свободные ячейки
        while (осталось > 0)
        {
            ЗаписьИнвентаря свободная = _предметы.Find(запись => запись.пуста);
            if (свободная == null)
            {
                if (количествоЯчеек > 0) break;
                свободная = new ЗаписьИнвентаря();
                _предметы.Add(свободная);
            }

            int влезет = Mathf.Min(осталось, максимум);
            свободная.вещь = вещь;
            свободная.название = вещь != null ? "" : имя;
            свободная.количество = влезет;
            осталось -= влезет;
        }

        последнийПредмет = имя;
        последняяВещь = вещь;

        if (осталось < сколько)
        {
            _приДобавлении.Вызвать();
            Сообщить();
        }
        if (осталось > 0) _приНехваткеМеста.Вызвать();

        return осталось;
    }

    /// <summary>
    /// Забирает предметы и даёт "да". Если предметов не хватает, ничего не забирает и даёт "нет"
    /// </summary>
    public Флажок Убрать(Строка название, Число сколько)
    {
        if (!Есть(название, сколько)) return нет;

        int осталось = сколько;
        // Забираем с конца, чтобы первые ячейки оставались заполненными
        for (int i = _предметы.Count - 1; i >= 0 && осталось > 0; i--)
        {
            ЗаписьИнвентаря запись = _предметы[i];
            if (запись.пуста || запись.имя != название) continue;

            int забрать = Mathf.Min(осталось, запись.количество);
            запись.количество -= забрать;
            осталось -= забрать;

            if (запись.количество <= 0)
            {
                последняяВещь = запись.вещь;
                if (количествоЯчеек > 0) запись.Опустошить();
                else _предметы.RemoveAt(i);
            }
        }

        последнийПредмет = название;
        Сообщить();
        return да;
    }

    /// <summary>
    /// Забирает вещи и даёт "да". Если вещей не хватает, ничего не забирает и даёт "нет"
    /// </summary>
    public Флажок Убрать(Вещь вещь, Число сколько) => вещь != null && Убрать(вещь.name, сколько);

    /// <summary>
    /// Меняет местами содержимое двух ячеек
    /// </summary>
    public void Поменять(Число первая, Число вторая)
    {
        if (Ячейка(первая) == null || Ячейка(вторая) == null) return;

        (_предметы[первая], _предметы[вторая]) = (_предметы[вторая], _предметы[первая]);
        Сообщить();
    }

    /// <summary>
    /// Выбрасывает все предметы
    /// </summary>
    public void Очистить()
    {
        _предметы.Clear();
        ПодогнатьЯчейки();
        Сообщить();
    }
}

#if UNITY_EDITOR
[CustomPropertyDrawer(typeof(ЗаписьИнвентаря))]
internal class ЗаписьИнвентаряDrawer : PropertyDrawer
{
    public override void OnGUI(Rect position, SerializedProperty property, GUIContent label)
    {
        SerializedProperty вещь = property.FindPropertyRelative("вещь");
        SerializedProperty название = property.FindPropertyRelative("название");
        SerializedProperty количество = property.FindPropertyRelative("количество");

        Rect строка = new Rect(position.x, position.y, position.width - 70, EditorGUIUtility.singleLineHeight);
        Rect число = new Rect(position.xMax - 65, position.y, 65, EditorGUIUtility.singleLineHeight);

        EditorGUI.PropertyField(строка, вещь, label);
        EditorGUI.PropertyField(число, количество, GUIContent.none);

        if (вещь.objectReferenceValue == null)
        {
            Rect имя = new Rect(position.x, position.y + EditorGUIUtility.singleLineHeight + 2, position.width, EditorGUIUtility.singleLineHeight);
            EditorGUI.PropertyField(имя, название, new GUIContent("  Или название"));
        }
    }

    public override float GetPropertyHeight(SerializedProperty property, GUIContent label)
    {
        bool безВещи = property.FindPropertyRelative("вещь").objectReferenceValue == null;
        return EditorGUIUtility.singleLineHeight * (безВещи ? 2 : 1) + (безВещи ? 2 : 0);
    }
}

[CanEditMultipleObjects]
[CustomEditor(typeof(Инвентарь))]
internal class ИнвентарьEditor : RunityEditor<Инвентарь>
{
    protected override void Отрисовать()
    {
        Текст("Этот объект хранит вещи. Создайте их через Create - Runity - Вещь. Положить вещь можно компонентом Подбираемое или через события, а показать - Ячейкой инвентаря или Блоком инвентаря");

        Пробел();

        Поле("Количество ячеек", x => x.количествоЯчеек,
            (title, value) => EditorGUILayout.IntField(title, value));

        Пробел();

        НачатьСобытия();
        ОтобразитьСвойство("Предметы", "_предметы");
        Пробел();
        ОтобразитьСобытие("При изменении", "_приИзменении");
        ОтобразитьСобытие("При добавлении", "_приДобавлении");
        ОтобразитьСобытие("При нехватке места", "_приНехваткеМеста");
        ЗакончитьСобытия();
    }
}
