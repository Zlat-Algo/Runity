using System;
#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;

/// <summary>
/// Зона, которая ранит или лечит того, кто в ней стоит: лава, ядовитое болото, костёр, целебный родник.
/// Кто зашёл в зону, сообщает компонент Касание. Урон идёт, пока стоишь в зоне, а лечение - пока здоровье не станет полным
/// </summary>
[DisallowMultipleComponent]
[RequireComponent(typeof(Касание))]
[AddComponentMenu("  Runity/ Механики/ Бой/Зона здоровья")]
public class ЗонаЗдоровья : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() => здоровье = null;

    [SerializeField] Число _изменение = -1;
    /// <summary>
    /// Сколько здоровья добавлять за раз. Если меньше нуля, зона ранит
    /// </summary>
    public Число изменение { get => _изменение; set => _изменение = value; }

    [SerializeField] Дробное _интервал = 0.5f;
    /// <summary>
    /// Через сколько секунд повторять урон или лечение
    /// </summary>
    public Дробное интервал { get => _интервал; set => _интервал = value; }

    [SerializeField] Дробное _задержка = 0;
    /// <summary>
    /// Через сколько секунд после входа в зону срабатывает первый раз. 0 - сразу
    /// </summary>
    public Дробное задержка { get => _задержка; set => _задержка = value; }

    /// <summary>
    /// Здоровье того, на кого зона действует сейчас. Пусто, если ни на кого
    /// </summary>
    public Здоровье цель => здоровье;

    Касание касание;
    Здоровье здоровье;
    Action действие;

    void Awake()
    {
        касание = GetComponent<Касание>();
        действие = Изменить;
    }

    void Update()
    {
        // Кто-то зашёл, а зона ещё не действует - начинаем
        if (здоровье != null || !касание.внутри || касание.последний == null) return;
        здоровье = касание.последний.GetComponentInParent<Здоровье>();
        if (здоровье == null) return;

        if (изменение < 0)
        {
            // Урон идёт, пока цель стоит в зоне
            ВызыватьСЗадержкойПока(действие, () => Продолжать(касание.внутри), задержка, интервал);
        }
        else
        {
            // Лечение идёт, пока здоровье не станет полным или цель не уйдёт
            ВызыватьСЗадержкойДо(действие, () => !Продолжать(касание.внутри && здоровье.текущее < здоровье.максимальное), задержка, интервал);
        }
    }

    void Изменить()
    {
        if (здоровье == null) return;
        if (изменение < 0) здоровье.ПолучитьУрон(-(int)изменение);
        else здоровье.Вылечить(изменение);
    }

    // Когда вызовы заканчиваются, зона снова готова встретить следующего
    bool Продолжать(bool условие)
    {
        if (!условие || здоровье == null) здоровье = null;
        return здоровье != null;
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(ЗонаЗдоровья))]
internal class ЗонаЗдоровьяEditor : RunityEditor<ЗонаЗдоровья>
{
    protected override void Отрисовать()
    {
        Текст(компонент.изменение < 0 ? "Эта зона ранит того, кто в ней стоит" : "Эта зона лечит того, кто в ней стоит, пока здоровье не станет полным");

        Пробел();

        Поле("Изменение", x => x.изменение, (title, value) => EditorGUILayout.IntField(title, value));
        Поле("Интервал", x => x.интервал, (title, value) => EditorGUILayout.FloatField(title, value));
        Поле("Задержка", x => x.задержка, (title, value) => EditorGUILayout.FloatField(title, value));
    }
}
#endif
