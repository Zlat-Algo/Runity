#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;
using UnityEngine.Events;

public enum ДействиеПриПотереЗдоровья { УдалениеСебя, ПерезапускСцены, УказанноеДействие}

/// <summary>
/// Хранит здоровье объекта и решает, что будет, когда оно закончится
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Механики/ Бой/Здоровье")]
public class Здоровье : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    /// <summary>
    /// Сколько здоровья есть сейчас
    /// </summary>
    [SerializeField] int _текущее = 10;
    public int текущее
    {
        get => _текущее;
        set
        {
            if (!Application.isPlaying)
            {
                _текущее = value;
                return;
            }

            int прошлое = _текущее;
            _текущее = Mathf.Clamp(value, 0, максимальное);

            if (_текущее == прошлое) return;

            _приИзмененииЗдоровья.Вызвать();
            if (_текущее < прошлое)
            {
                _приУроне.Вызвать();
            }
            else
            {
                _приЛечении.Вызвать();
            }

            if (_текущее == 0)
            {
                _когдаЗакончилосьЗдоровье.Вызвать();
                switch (действиеПриПотереЗдоровья)
                {
                    case ДействиеПриПотереЗдоровья.УдалениеСебя:
                        Удалить(весьОбъект);
                        break;
                    case ДействиеПриПотереЗдоровья.ПерезапускСцены:
                        Сцены.Перезапустить();
                        break;
                    case ДействиеПриПотереЗдоровья.УказанноеДействие:
                        break;
                }
            }
        }
    }

    /// <summary>
    /// Больше этого значения здоровье не поднимется
    /// </summary>
    [SerializeField] int _максимальное = 10;
    public int максимальное { get => _максимальное; set => _максимальное = value; }

    /// <summary>
    /// Что произойдёт, когда здоровье закончится
    /// </summary>
    [SerializeField] ДействиеПриПотереЗдоровья _действиеПриПотереЗдоровья;
    public ДействиеПриПотереЗдоровья действиеПриПотереЗдоровья { get => _действиеПриПотереЗдоровья; set => _действиеПриПотереЗдоровья = value; }

    /// <summary>
    /// Срабатывает, когда здоровье дошло до нуля
    /// </summary>
    [SerializeField] События _когдаЗакончилосьЗдоровье;
    public События когдаЗакончилосьЗдоровье => _когдаЗакончилосьЗдоровье;

    [SerializeField] События _приИзмененииЗдоровья;
    /// <summary>
    /// Срабатывает при любом изменении здоровья
    /// </summary>
    public События приИзмененииЗдоровья => _приИзмененииЗдоровья;

    [SerializeField] События _приУроне;
    /// <summary>
    /// Срабатывает, когда здоровье уменьшилось
    /// </summary>
    public События приУроне => _приУроне;

    [SerializeField] События _приЛечении;
    /// <summary>
    /// Срабатывает, когда здоровье увеличилось
    /// </summary>
    public События приЛечении => _приЛечении;

    [SerializeField] Флажок _бессмертие;
    /// <summary>
    /// Пока "да", объект не получает урон
    /// </summary>
    public Флажок бессмертие { get => _бессмертие; set => _бессмертие = value; }

    /// <summary>
    /// Здоровье от 0 до 1. Удобно для полосок здоровья
    /// </summary>
    public Дробное доля => максимальное > 0 ? (float)текущее / максимальное : 0;

    /// <summary>
    /// Отнимает указанное количество здоровья
    /// </summary>
    public void ПолучитьУрон(Число урон)
    {
        if (бессмертие) return;
        текущее -= урон;
    }
    /// <summary>
    /// Отнимает случайное количество здоровья из диапазона
    /// </summary>
    public void ПолучитьУрон(Число уронМинимальный, Число уронМаксимальный)
    {
        if (бессмертие) return;
        текущее -= Случайности.СлучайноеИзДиапазона(уронМинимальный, уронМаксимальный);
    }
    /// <summary>
    /// Прибавляет здоровье, но не больше максимального
    /// </summary>
    public void Вылечить(Число количество)
    {
        текущее += количество;
    }
    /// <summary>
    /// Восстанавливает здоровье до максимального
    /// </summary>
    public void ВылечитьПолностью()
    {
        текущее = максимальное;
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(Здоровье))]
internal class ЗдоровьеEditor : RunityEditor<Здоровье>
{
    protected override void Отрисовать()
    {
        Текст("Этот объект имеет определённое количество здоровья и что-то сделает при его потере");

        Пробел();

        Поле("Текущее", x => x.текущее,
            (title, value) => EditorGUILayout.IntField(title, value));

        Поле("Максимальное", x => x.максимальное,
            (title, value) => EditorGUILayout.IntField(title, value));

        Поле("Бессмертие", x => x.бессмертие,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Пробел();

        Поле("Действие при потере здоровья", x => x.действиеПриПотереЗдоровья,
            (title, value) => (ДействиеПриПотереЗдоровья)EditorGUILayout.EnumPopup(title, value));

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("Когда закончилось здоровье", "_когдаЗакончилосьЗдоровье");
        ОтобразитьСобытие("При изменении здоровья", "_приИзмененииЗдоровья");
        ОтобразитьСобытие("При уроне", "_приУроне");
        ОтобразитьСобытие("При лечении", "_приЛечении");
        ЗакончитьСобытия();
    }
}
#endif
