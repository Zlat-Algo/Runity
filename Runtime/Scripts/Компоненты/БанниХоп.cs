#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;

/// <summary>
/// Банни-хоп как в CS2: скорость набирается стрейфом в воздухе, а прыжок ровно в момент приземления не даёт трению её съесть
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Передвижение/ Персонаж/Банни-хоп")]
public class БанниХоп : РасширениеПерсонажа
{
    // Движение Source считается в дюймах: 1 единица = 0.0254 метра. Все постоянные ниже взяты из CS2 и переведены в метры
    const float единица = 0.0254f;
    const float скоростьОстановки = 80 * единица;
    const float пределРазгонаВВоздухе = 30 * единица;
    const float опорнаяСкорость = 250 * единица;
    const float вертикальнаяСкоростьМёртвогоСтрейфа = 140 * единица;
    const float максимумСтамины = 80;
    const float ценаПрыжка = 0.08f;
    const float ценаПриземления = 0.05f;
    const float восстановлениеСтамины = 60;

    [SerializeField] Дробное _ускорениеНаЗемле = 5.5;
    /// <summary>
    /// Как быстро персонаж разгоняется на земле. В CS2 это sv_accelerate = 5.5
    /// </summary>
    public Дробное ускорениеНаЗемле { get => _ускорениеНаЗемле; set => _ускорениеНаЗемле = value; }

    [SerializeField] Дробное _ускорениеВВоздухе = 12;
    /// <summary>
    /// Насколько сильно работает стрейф в воздухе. В CS2 это sv_airaccelerate = 12
    /// </summary>
    public Дробное ускорениеВВоздухе { get => _ускорениеВВоздухе; set => _ускорениеВВоздухе = value; }

    [SerializeField] Дробное _трение = 5.2;
    /// <summary>
    /// Как быстро персонаж тормозит на земле. В CS2 это sv_friction = 5.2
    /// </summary>
    public Дробное трение { get => _трение; set => _трение = value; }

    [SerializeField] Число _тиковВСекунду = 64;
    /// <summary>
    /// Сколько раз в секунду считается движение. В CS2 это 64, от этого зависит сила стрейфа
    /// </summary>
    public Число тиковВСекунду { get => _тиковВСекунду; set => _тиковВСекунду = Mathf.Max(1, value); }

    [SerializeField] Флажок _стамина = да;
    /// <summary>
    /// Если "да", то прыжки подряд становятся ниже и медленнее, как в CS2. Выключите, чтобы прыгать без усталости
    /// </summary>
    public Флажок стамина { get => _стамина; set => _стамина = value; }

    [SerializeField] Флажок _ограничениеСкорости = да;
    /// <summary>
    /// Если "да", то при прыжке скорость обрезается до 1.1 от обычной, как на официальных серверах CS2. Выключите, чтобы разгоняться без предела
    /// </summary>
    public Флажок ограничениеСкорости { get => _ограничениеСкорости; set => _ограничениеСкорости = value; }

    [SerializeField] Флажок _автоПрыжок = нет;
    /// <summary>
    /// Если "да", то при зажатом пробеле персонаж сам прыгает в момент приземления. В CS2 это sv_autobunnyhopping
    /// </summary>
    public Флажок автоПрыжок { get => _автоПрыжок; set => _автоПрыжок = value; }

    [SerializeField] Флажок _прыжокКолесом = да;
    /// <summary>
    /// Если "да", то прыгать можно прокруткой колёсика мыши. Так в CS2 проще попасть прыжком в момент приземления
    /// </summary>
    public Флажок прыжокКолесом { get => _прыжокКолесом; set => _прыжокКолесом = value; }

    [SerializeField] События _приИдеальномПрыжке;
    /// <summary>
    /// Срабатывает, когда прыжок пришёлся ровно на момент приземления и скорость не потерялась
    /// </summary>
    public События приИдеальномПрыжке => _приИдеальномПрыжке;

    [SerializeField] События _приСрывеСерии;
    /// <summary>
    /// Срабатывает, когда персонаж опоздал с прыжком и трение начало съедать скорость
    /// </summary>
    public События приСрывеСерии => _приСрывеСерии;

    /// <summary>
    /// Текущая скорость персонажа по земле
    /// </summary>
    public Дробное скорость => скорость3.magnitude;

    /// <summary>
    /// Сколько идеальных прыжков подряд сделано
    /// </summary>
    public Число серия { get; private set; }

    /// <summary>
    /// Текущая усталость: от 0 до 80. Чем больше, тем ниже и медленнее прыжки
    /// </summary>
    public Дробное усталость => стаминаСейчас;

    Vector3 скорость3;
    float стаминаСейчас;
    float копилкаВремени;
    bool прыгнулВЭтомКадре;
    int кадровНаЗемле = 1;

    float МаксимальнаяСкорость()
    {
        float максимум = персонаж.скорость;
        if (стамина && стаминаСейчас > 0)
        {
            float s = Mathf.Clamp01(1 - стаминаСейчас / 100);
            максимум *= s * s;
        }
        return максимум;
    }

    protected internal override Vector3 ИзменитьДвижение(Vector3 желаемое)
    {
        bool наЗемле = персонаж.наЗемле && !прыгнулВЭтомКадре;
        прыгнулВЭтомКадре = false;

        if (наЗемле)
        {
            кадровНаЗемле++;
            if (кадровНаЗемле == 1 && серия > 0)
            {
                серия = 0;
                _приСрывеСерии.Вызвать();
            }
        }

        float тик = 1f / тиковВСекунду;
        копилкаВремени += Время.времяСПрошлогоКадра;

        while (копилкаВремени >= тик)
        {
            копилкаВремени -= тик;
            Тик(желаемое, наЗемле, тик);
        }

        return скорость3;
    }

    void Тик(Vector3 желаемое, bool наЗемле, float тик)
    {
        if (стаминаСейчас > 0) стаминаСейчас = Mathf.Max(0, стаминаСейчас - восстановлениеСтамины * тик);

        float максимум = МаксимальнаяСкорость();
        Vector3 направление = желаемое.sqrMagnitude > 0.000001f ? желаемое.normalized : Vector3.zero;
        float желаемаяСкорость = Mathf.Min(желаемое.magnitude, максимум);

        if (наЗемле)
        {
            Трение(тик);
            Разгон(направление, желаемаяСкорость, тик);
            if (скорость3.magnitude > максимум) скорость3 = скорость3.normalized * максимум;
            if (скорость3.magnitude < единица) скорость3 = Vector3.zero;
        }
        else
        {
            // В начале прыжка CS2 ослабляет стрейф в четыре раза, игроки называют это мёртвым стрейфом
            float вертикальная = персонаж.вертикальнаяСкорость;
            float поверхность = вертикальная > 0 && вертикальная <= вертикальнаяСкоростьМёртвогоСтрейфа ? 0.25f : 1;
            РазгонВВоздухе(направление, желаемаяСкорость, поверхность, тик);
        }
    }

    void Трение(float тик)
    {
        float сейчас = скорость3.magnitude;
        if (сейчас < 0.1f * единица) return;

        float опора = сейчас < скоростьОстановки ? скоростьОстановки : сейчас;
        float новая = Mathf.Max(0, сейчас - опора * трение * тик);
        скорость3 *= новая / сейчас;
    }

    void Разгон(Vector3 направление, float желаемаяСкорость, float тик)
    {
        float добавить = желаемаяСкорость - Vector3.Dot(скорость3, направление);
        if (добавить <= 0) return;

        float разгон = ускорениеНаЗемле * тик * Mathf.Max(опорнаяСкорость, желаемаяСкорость);
        скорость3 += Mathf.Min(разгон, добавить) * направление;
    }

    // Разгон ограничен проекцией скорости на направление ввода. Поэтому стрейф поперёк движения добавляет скорость, а нажатие вперёд нет
    void РазгонВВоздухе(Vector3 направление, float желаемаяСкорость, float поверхность, float тик)
    {
        float предел = Mathf.Min(желаемаяСкорость, пределРазгонаВВоздухе);
        float добавить = предел - Vector3.Dot(скорость3, направление);
        if (добавить <= 0) return;

        float разгон = ускорениеВВоздухе * желаемаяСкорость * тик * поверхность;
        скорость3 += Mathf.Min(разгон, добавить) * направление;
    }

    protected internal override bool ХочетПрыгнуть()
    {
        if (автоПрыжок && Управление.пробелУдерживается) return да;
        return прыжокКолесом && (Управление.КлавишаНажата(Клавиша.КолесоВверх) || Управление.КлавишаНажата(Клавиша.КолесоВниз));
    }

    protected internal override void ПриПрыжке()
    {
        bool идеальный = кадровНаЗемле == 0;
        if (идеальный)
        {
            серия++;
            _приИдеальномПрыжке.Вызвать();
        }

        if (ограничениеСкорости)
        {
            float предел = 1.1f * персонаж.скорость;
            if (скорость3.magnitude > предел) скорость3 = скорость3.normalized * предел;
        }

        float толчок = персонаж.силаПрыжка;
        if (стамина && стаминаСейчас > 0) толчок *= Mathf.Clamp01(1 - стаминаСейчас / 100);
        персонаж.Подбросить(толчок);

        if (стамина) стаминаСейчас = Mathf.Min(максимумСтамины, стаминаСейчас + ценаПрыжка * (персонаж.силаПрыжка / единица));

        прыгнулВЭтомКадре = да;
        кадровНаЗемле = 1;
    }

    protected internal override void ПриПриземлении()
    {
        float скоростьПадения = -персонаж.вертикальнаяСкорость / единица;
        if (стамина && скоростьПадения > 0) стаминаСейчас = Mathf.Min(максимумСтамины, стаминаСейчас + ценаПриземления * скоростьПадения);

        // Ноль означает, что игрок ещё может успеть прыгнуть, не потеряв скорость
        кадровНаЗемле = 0;
    }

    /// <summary>
    /// Ставит Персонажу скорость, гравитацию, силу прыжка и размеры как у игрока в CS2
    /// </summary>
    public void НастроитьКакВCS2()
    {
        персонаж.скорость = 250 * единица;
        персонаж.гравитация = 800 * единица;
        персонаж.силаПрыжка = 301.993377f * единица;
        персонаж.высота = 72 * единица;
        персонаж.радиус = 16 * единица;
        персонаж.высотаСтупеньки = 18 * единица;
        персонаж.крутизнаСклона = 45.57f;
    }

    /// <summary>
    /// Сразу сбрасывает набранную скорость и усталость
    /// </summary>
    public void СброситьСкорость()
    {
        скорость3 = Vector3.zero;
        стаминаСейчас = 0;
        серия = 0;
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(БанниХоп))]
internal class БанниХопEditor : RunityEditor<БанниХоп>
{
    protected override void Отрисовать()
    {
        Текст("Этот компонент делает движение Персонажа как в CS2. Скорость набирается в воздухе: не жмите вперёд, а зажимайте A или D и плавно ведите мышь в ту же сторону. Прыгать нужно ровно в момент приземления, проще всего колёсиком мыши");

        Пробел();

        if (GUILayout.Button(Подпись("Настроить Персонажа как в CS2", nameof(БанниХоп.НастроитьКакВCS2))))
        {
            foreach (БанниХоп хоп in components)
            {
                Undo.RecordObjects(new Object[] { хоп.персонаж, хоп.персонаж.оригинал }, "Настроить как в CS2");
                хоп.НастроитьКакВCS2();
                EditorUtility.SetDirty(хоп.персонаж);
                EditorUtility.SetDirty(хоп.персонаж.оригинал);
            }
        }

        Пробел();

        Поле("Ускорение на земле", x => x.ускорениеНаЗемле,
            (title, value) => EditorGUILayout.FloatField(title, value));

        Поле("Ускорение в воздухе", x => x.ускорениеВВоздухе,
            (title, value) => EditorGUILayout.FloatField(title, value));

        Поле("Трение", x => x.трение,
            (title, value) => EditorGUILayout.FloatField(title, value));

        Поле("Тиков в секунду", x => x.тиковВСекунду,
            (title, value) => EditorGUILayout.IntField(title, value));

        Пробел();

        Поле("Стамина", x => x.стамина,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Поле("Ограничение скорости", x => x.ограничениеСкорости,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Поле("Автопрыжок", x => x.автоПрыжок,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Поле("Прыжок колесом", x => x.прыжокКолесом,
            (title, value) => EditorGUILayout.Toggle(title, value));

        if (Application.isPlaying)
        {
            Пробел();
            Текст($"Скорость: {(float)компонент.скорость:0.00}   Серия: {компонент.серия}   Усталость: {(float)компонент.усталость:0}");
        }

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("При идеальном прыжке", "_приИдеальномПрыжке");
        ОтобразитьСобытие("При срыве серии", "_приСрывеСерии");
        ЗакончитьСобытия();
    }

    public override bool RequiresConstantRepaint() => Application.isPlaying;
}
