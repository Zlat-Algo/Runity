#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;
using UnityEngine.Serialization;
using UnityEngine.UI;

/// <summary>
/// Проигрывает Кадровую анимацию на Спрайтере или картинке интерфейса на этом объекте
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Анимация/Проигрыватель кадров")]
public class ПроигрывательКадров : RunityComponent
{
    protected override void OnEnable()
    {
        if (играетНаСтарте) Запустить();
        else ПоказатьКадр(0);
    }
    protected override void OnDisable() { }

    [SerializeField, FormerlySerializedAs("clip")] КадроваяАнимация _анимация;
    /// <summary>
    /// Какая анимация проигрывается. При смене новая анимация запускается сначала
    /// </summary>
    public КадроваяАнимация анимация
    {
        get => _анимация;
        set
        {
            if (_анимация == value) return;

            _анимация = value;
            if (Application.isPlaying) Запустить();
        }
    }

    [SerializeField, FormerlySerializedAs("playOnEnable")] Флажок _играетНаСтарте = да;
    /// <summary>
    /// Если "да", то анимация запускается при появлении объекта
    /// </summary>
    public Флажок играетНаСтарте { get => _играетНаСтарте; set => _играетНаСтарте = value; }

    [SerializeField] Дробное _скорость = 1;
    /// <summary>
    /// Скорость проигрывания: 1 - обычная, 2 - в два раза быстрее
    /// </summary>
    public Дробное скорость { get => _скорость; set => _скорость = value; }

    [SerializeField] События _приЗавершении;
    /// <summary>
    /// Срабатывает, когда анимация без повтора дошла до конца
    /// </summary>
    public События приЗавершении => _приЗавершении;

    [SerializeField] События _приПовторе;
    /// <summary>
    /// Срабатывает каждый раз, когда анимация с повтором начинается заново
    /// </summary>
    public События приПовторе => _приПовторе;

    /// <summary>
    /// Даёт "да", пока анимация проигрывается
    /// </summary>
    public Флажок играет { get; private set; }

    /// <summary>
    /// Номер текущего кадра, считая с нуля
    /// </summary>
    public Число текущийКадр { get; private set; }

    float таймер;

    void Update()
    {
        if (!играет || анимация == null || анимация.количествоКадров == 0) return;

        таймер += Время.времяСПрошлогоКадра * скорость;

        float длительностьКадра = 1f / анимация.кадровВСекунду;

        while (таймер >= длительностьКадра && играет)
        {
            таймер -= длительностьКадра;
            СледующийКадр();
        }
    }

    /// <summary>
    /// Запускает анимацию сначала
    /// </summary>
    public void Запустить()
    {
        if (анимация == null || анимация.количествоКадров == 0)
        {
            играет = нет;
            return;
        }

        текущийКадр = 0;
        таймер = 0;
        играет = да;
        ПоказатьКадр(0);
    }

    /// <summary>
    /// Запускает другую анимацию сначала
    /// </summary>
    public void Запустить(КадроваяАнимация новаяАнимация)
    {
        _анимация = новаяАнимация;
        Запустить();
    }

    /// <summary>
    /// Запускает другую анимацию, только если сейчас играет не она. Удобно вызывать каждый кадр
    /// </summary>
    public void Переключить(КадроваяАнимация новаяАнимация)
    {
        if (_анимация != новаяАнимация) Запустить(новаяАнимация);
    }

    /// <summary>
    /// Ставит анимацию на паузу
    /// </summary>
    public void Приостановить() => играет = нет;

    /// <summary>
    /// Продолжает анимацию с того места, где была пауза
    /// </summary>
    public void Продолжить() => играет = анимация != null && анимация.количествоКадров > 0;

    /// <summary>
    /// Останавливает анимацию и возвращает первый кадр
    /// </summary>
    public void Остановить()
    {
        играет = нет;
        таймер = 0;
        текущийКадр = 0;
        ПоказатьКадр(0);
    }

    /// <summary>
    /// Показывает указанный кадр
    /// </summary>
    public void ПоказатьКадр(Число номер)
    {
        if (анимация == null || анимация.количествоКадров == 0) return;

        текущийКадр = Математика.Ограничить(номер, 0, анимация.количествоКадров - 1);

        Sprite спрайт = анимация.ПолучитьСпрайт(текущийКадр);

        if (TryGetComponent(out SpriteRenderer отрисовщик)) отрисовщик.sprite = спрайт;
        if (TryGetComponent(out Image картинка)) картинка.sprite = спрайт;
    }

    void СледующийКадр()
    {
        int следующий = текущийКадр + 1;

        if (следующий >= анимация.количествоКадров)
        {
            if (анимация.повторять)
            {
                следующий = 0;
                _приПовторе.Вызвать();
            }
            else
            {
                играет = нет;
                _приЗавершении.Вызвать();
                return;
            }
        }

        ПоказатьКадр(следующий);
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(ПроигрывательКадров))]
internal class ПроигрывательКадровEditor : RunityEditor<ПроигрывательКадров>
{
    protected override void Отрисовать()
    {
        Текст("Этот объект проигрывает Кадровую анимацию. Создайте её через Create - Runity - Кадровая анимация. Рядом должен быть Спрайтер или картинка интерфейса");

        Пробел();

        Поле("Анимация", x => x.анимация,
            (title, value) => ПолеОбъекта<КадроваяАнимация>(title, value));

        Поле("Играет на старте", x => x.играетНаСтарте,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Поле("Скорость", x => x.скорость,
            (title, value) => EditorGUILayout.FloatField(title, value));

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("При завершении", "_приЗавершении");
        ОтобразитьСобытие("При повторе", "_приПовторе");
        ЗакончитьСобытия();
    }
}
#endif
