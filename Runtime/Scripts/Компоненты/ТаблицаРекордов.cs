        Поле("Больше - лучше", x => x.большеЛучше, (title, value) => EditorGUILayout.Toggle(title, value));
        Поле("Имя игрока", x => x.имяИгрока, (title, value) => EditorGUILayout.TextField(title, value));

        Пробел();

        Поле("Текст", x => x.текст, (title, value) => ПолеОбъекта<Graphic>(title, value, true));
        Поле("Показывать как время", x => x.показыватьКакВремя, (title, value) => EditorGUILayout.Toggle(title, value));

        Пробел();

        Текст((string)компонент.ТекстТаблицы());
        Кнопка("Очистить таблицу", x => x.Очистить());

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("При новом рекорде", "_приНовомРекорде");
        ОтобразитьСобытие("При попадании в таблицу", "_приПопаданииВТаблицу");
        ЗакончитьСобытия();
    }
}
