using System;
using System.Collections.Generic;
using System.Text;
#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// Одна строка таблицы рекордов: кто и сколько набрал
/// </summary>
[Serializable]
public class Рекорд
{
    /// <summary>
    /// Имя игрока
    /// </summary>
    public string имя;

    /// <summary>
    /// Очки или время
    /// </summary>
    public float результат;

    /// <summary>
    /// Когда поставлен рекорд
    /// </summary>
    public string дата;
}

/// <summary>
/// Таблица рекордов (лидеров): лучшие результаты с именами игроков. Хранится на этом компьютере между запусками игры и выводится в текст
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Механики/Таблица Рекордов")]
public class ТаблицаРекордов : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [Serializable]
    class Список { public List<Рекорд> строки = new List<Рекорд>(); }

    [SerializeField] Строка _названиеТаблицы = "Рекорды";
    /// <summary>
    /// Под каким именем таблица хранится. Для разных уровней или режимов - разные названия
    /// </summary>
    public Строка названиеТаблицы { get => _названиеТаблицы; set { _названиеТаблицы = value; Загрузить(); } }

    [SerializeField] int _мест = 10;
    /// <summary>
    /// Сколько лучших результатов хранить
    /// </summary>
    public Число мест { get => _мест; set => _мест = Mathf.Max(1, (int)value); }

    [SerializeField] Флажок _большеЛучше = да;
    /// <summary>
    /// "Да" для очков: чем больше, тем лучше. "Нет" для времени: чем меньше, тем лучше
    /// </summary>
    public Флажок большеЛучше { get => _большеЛучше; set => _большеЛучше = value; }

    [SerializeField] Строка _имяИгрока = "Игрок";
    /// <summary>
    /// Под каким именем записывать следующий результат. Его можно менять из Ввода текста через события
    /// </summary>
    public Строка имяИгрока { get => _имяИгрока; set => _имяИгрока = value; }

    [SerializeField] Graphic _текст;
    /// <summary>
    /// Текст, в который выводится таблица. Если пусто, берётся текст с этого же объекта
    /// </summary>
    public Graphic текст { get => _текст; set { _текст = value; ОбновитьТекст(); } }

    [SerializeField] Флажок _показыватьКакВремя = нет;
    /// <summary>
    /// Если "да", результаты пишутся как время (01:23), а не как числа
    /// </summary>
    public Флажок показыватьКакВремя { get => _показыватьКакВремя; set { _показыватьКакВремя = value; ОбновитьТекст(); } }

    [SerializeField] События _приНовомРекорде;
    /// <summary>
    /// Срабатывает, когда результат занял первое место
    /// </summary>
    public События приНовомРекорде => _приНовомРекорде;

    [SerializeField] События _приПопаданииВТаблицу;
    /// <summary>
    /// Срабатывает, когда результат попал в таблицу
    /// </summary>
    public События приПопаданииВТаблицу => _приПопаданииВТаблицу;

    Список список = new Список();

    /// <summary>
    /// Все строки таблицы, от лучшей к худшей
    /// </summary>
    public IReadOnlyList<Рекорд> строки => список.строки;

    /// <summary>
    /// Лучший результат. Пусто, если таблица пустая
    /// </summary>
    public Рекорд лучший => список.строки.Count > 0 ? список.строки[0] : null;

    /// <summary>
    /// Какое место занял последний добавленный результат, считая с 1. 0 - не попал в таблицу
    /// </summary>
    public Число последнееМесто { get; private set; }

    string ключ => "Runity.Рекорды." + (string)названиеТаблицы;

    void Awake() => Загрузить();

    void Start()
    {
        if (текст == null) _текст = ЗаписьТекста.НайтиРядом(this);
        ОбновитьТекст();
    }

    void Загрузить()
    {
        string данные = PlayerPrefs.GetString(ключ, "");
        список = string.IsNullOrEmpty(данные) ? new Список() : JsonUtility.FromJson<Список>(данные) ?? new Список();
    }

    void Сохранить()
    {
        PlayerPrefs.SetString(ключ, JsonUtility.ToJson(список));
        PlayerPrefs.Save();
    }

    /// <summary>
    /// Записывает результат под именем из «Имя игрока»
    /// </summary>
    public void Добавить(Дробное результат) => Добавить(имяИгрока, результат);

    /// <summary>
    /// Записывает результат под указанным именем. Если он не лучше худшего из таблицы, а мест уже нет, он не попадает в таблицу
    /// </summary>
    public void Добавить(Строка имя, Дробное результат)
    {
        Рекорд новый = new Рекорд { имя = имя, результат = результат, дата = DateTime.Now.ToString("dd.MM.yyyy") };
        int место = список.строки.FindIndex(р => большеЛучше ? новый.результат > р.результат : новый.результат < р.результат);
        if (место < 0) место = список.строки.Count;
        if (место >= (int)мест)
        {
            последнееМесто = 0;
            return;
        }

        список.строки.Insert(место, новый);
        if (список.строки.Count > (int)мест) список.строки.RemoveRange(мест, список.строки.Count - (int)мест);
        последнееМесто = место + 1;
        Сохранить();
        ОбновитьТекст();

        _приПопаданииВТаблицу.Вызвать();
        if (место == 0) _приНовомРекорде.Вызвать();
    }

    /// <summary>
    /// Записывает текущее число Счётчика, например очки за уровень
    /// </summary>
    public void ДобавитьИзСчётчика(Счётчик счётчик) { if (счётчик != null) Добавить((float)(int)счётчик.значение); }

    /// <summary>
    /// Записывает время Секундомера, например время прохождения уровня
    /// </summary>
    public void ДобавитьИзСекундомера(Секундомер секундомер) { if (секундомер != null) Добавить(секундомер.прошло); }

    /// <summary>
    /// Даёт "да", если результат попадёт в таблицу
    /// </summary>
    public Флажок ПопадётВТаблицу(Дробное результат) =>
        список.строки.Count < (int)мест || (большеЛучше ? (float)результат > список.строки[список.строки.Count - 1].результат : (float)результат < список.строки[список.строки.Count - 1].результат);

    /// <summary>
    /// Стирает все рекорды этой таблицы
    /// </summary>
    public void Очистить()
    {
        список.строки.Clear();
        PlayerPrefs.DeleteKey(ключ);
        ОбновитьТекст();
    }

    /// <summary>
    /// Таблица в виде текста: «1. Вася - 120»
    /// </summary>
    public Строка ТекстТаблицы()
    {
        if (список.строки.Count == 0) return "Рекордов пока нет";
        StringBuilder текстТаблицы = new StringBuilder();
        for (int i = 0; i < список.строки.Count; i++)
        {
            Рекорд р = список.строки[i];
            string значение = показыватьКакВремя ? ЗаписьТекста.Время(р.результат, ФорматВремени.МинутыИСекунды, 2, false, false) : р.результат.ToString("0.##");
            текстТаблицы.AppendLine($"{i + 1}. {р.имя} - {значение}");
        }
        return текстТаблицы.ToString().TrimEnd();
    }

    void ОбновитьТекст()
    {
        if (текст != null) ЗаписьТекста.Записать(текст, ТекстТаблицы());
    }
}

