using UnityEngine;

/// <summary>
/// Создаёт копии объекта через равные промежутки времени
/// </summary>
[AddComponentMenu("  Runity/ Работа с объектами/ Создание и удаление/Спавнер")]
public class Спавнер : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    /// <summary>
    /// Пока "да", новые копии не создаются
    /// </summary>
    public bool пауза { get => _пауза; set => _пауза = value; }
    /// <summary>
    /// Какой объект копировать
    /// </summary>
    [SerializeField] bool _пауза;
    [Обязательное]
    public GameObject когоКопирует { get => _когоКопирует; set => _когоКопирует = value; }
    /// <summary>
    /// Сколько копий осталось создать. Отрицательное число означает, что копии бесконечны
    /// </summary>
    [SerializeField] GameObject _когоКопирует;
    public int количество { get => _количество; set => _количество = value; }
    [SerializeField] int _количество = -1;

    /// <summary>
    /// Минимальное время до первой копии
    /// </summary>
    public float времяДоСпавнаМинимальное { get => _времяДоСпавнаМинимальное; set => _времяДоСпавнаМинимальное = value; }
    /// <summary>
    /// Максимальное время до первой копии. Если оно больше минимального, время будет случайным
    /// </summary>
    [SerializeField] float _времяДоСпавнаМинимальное;
    public float времяДоСпавнаМаксимальное { get => _времяДоСпавнаМаксимальное; set => _времяДоСпавнаМаксимальное = value; }
    [SerializeField] float _времяДоСпавнаМаксимальное;
    /// <summary>
    /// Устаревшая настройка: время выбирается случайно, если максимум больше минимума
    /// </summary>
    public bool времяДоСпавнаСлучайное { get => _времяДоСпавнаСлучайное; set => _времяДоСпавнаСлучайное = value; }
    [SerializeField] bool _времяДоСпавнаСлучайное;

    /// <summary>
    /// Минимальное время между копиями
    /// </summary>
    public float времяМеждуСпавномМинимальное { get => _времяМеждуСпавномМинимальное; set => _времяМеждуСпавномМинимальное = value; }
    /// <summary>
    /// Максимальное время между копиями. Если оно больше минимального, время будет случайным
    /// </summary>
    [SerializeField] float _времяМеждуСпавномМинимальное;
    public float времяМеждуСпавномМаксимальное { get => _времяМеждуСпавномМаксимальное; set => _времяМеждуСпавномМаксимальное = value; }
    [SerializeField] float _времяМеждуСпавномМаксимальное;
    /// <summary>
    /// Устаревшая настройка: время выбирается случайно, если максимум больше минимума
    /// </summary>
    public bool времяМеждуСпавномСлучайное { get => _времяМеждуСпавномСлучайное; set => _времяМеждуСпавномСлучайное = value; }
    [SerializeField] bool _времяМеждуСпавномСлучайное;

    //public float уменьшениеТаймераПриСпавне { get => _уменьшениеТаймераПриСпавне; set => _уменьшениеТаймераПриСпавне = value; }
    //[SerializeField] float _уменьшениеТаймераПриСпавне;

    [SerializeField] События _приСпавне;
    /// <summary>
    /// Срабатывает сразу после создания каждой копии
    /// </summary>
    public События приСпавне => _приСпавне;

    /// <summary>
    /// Последняя созданная копия
    /// </summary>
    public GameObject последняяКопия { get; private set; }

    float осталосьДоСпавна;

    // Если максимум больше минимума, время выбирается случайно
    float ВыбратьВремя(float минимальное, float максимальное)
        => максимальное > минимальное ? Случайности.СлучайноеИзДиапазона(минимальное, максимальное) : минимальное;

    void Start()
    {
        осталосьДоСпавна = ВыбратьВремя(времяДоСпавнаМинимальное, времяДоСпавнаМаксимальное);
    }

    private void FixedUpdate()
    {
        if (пауза || количество == 0) return;

        осталосьДоСпавна -= Время.времяМеждуFixedUpdate;
        if (осталосьДоСпавна <= 0)
        {
            СоздатьКопию();
            осталосьДоСпавна = Mathf.Max(ВыбратьВремя(времяМеждуСпавномМинимальное, времяМеждуСпавномМаксимальное), Время.времяМеждуFixedUpdate);
            //времяМеждуСпавном.минимальное -= уменьшениеТаймераПриСпавне;
        }
    }

    void СоздатьКопию()
    {
        if (когоКопирует == null)
        {
            Консоль.НапечататьОшибку("Спавнеру не указано, кого копировать", this);
            количество = 0;
            return;
        }

        последняяКопия = Заспавнить(когоКопирует);
        if (количество > 0) количество--;
        _приСпавне.Вызвать();
    }

    /// <summary>
    /// Создаёт копию на следующем физическом кадре, не дожидаясь таймера
    /// </summary>
    public void СрочныйСпавн()
    {
        осталосьДоСпавна = 0;
    }
}

