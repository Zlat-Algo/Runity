#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;

/// <summary>
/// Что делает снаряд, когда врезается в препятствие
/// </summary>
public enum ДействиеСнарядаПриПрепятствии { Уничтожиться, Отскочить, ПролететьСквозь }

/// <summary>
/// Летит вперёд, наносит урон при попадании и уничтожается или отскакивает от препятствий
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Механики/ Бой/Снаряд")]
public class Снаряд : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] Дробное _скорость = 10;
    /// <summary>
    /// Как быстро летит снаряд
    /// </summary>
    public Дробное скорость { get => _скорость; set => _скорость = value; }

    [SerializeField] Число _урон = 1;
    /// <summary>
    /// Сколько здоровья отнимает попадание
    /// </summary>
    public Число урон { get => _урон; set => _урон = value; }

    [SerializeField] Дробное _времяЖизни = 3;
    /// <summary>
    /// Через сколько секунд снаряд удалится, если ни во что не попал
    /// </summary>
    public Дробное времяЖизни { get => _времяЖизни; set => _времяЖизни = value; }

    [SerializeField, HideInInspector] Строка _тегЦелей;

    [SerializeField] Теги _тегиЦелей = new Теги();
    /// <summary>
    /// Наносит урон только объектам с этими тегами. Если теги не выбраны, то любым объектам со Здоровьем
    /// </summary>
    public Теги тегиЦелей { get => _тегиЦелей; set => _тегиЦелей = value ?? new Теги(); }

    [SerializeField] Флажок _пролетаетСквозьЦели = нет;
    /// <summary>
    /// Если "да", то снаряд не исчезает при попадании и может задеть нескольких
    /// </summary>
    public Флажок пролетаетСквозьЦели { get => _пролетаетСквозьЦели; set => _пролетаетСквозьЦели = value; }

    [SerializeField] Теги _тегиПрепятствий = new Теги();
    /// <summary>
    /// Какие объекты считаются препятствиями. Если теги не выбраны, то препятствие - любой твёрдый объект, который не цель
    /// </summary>
    public Теги тегиПрепятствий { get => _тегиПрепятствий; set => _тегиПрепятствий = value ?? new Теги(); }

    [SerializeField] ДействиеСнарядаПриПрепятствии _приПрепятствии;
    /// <summary>
    /// Что делает снаряд, когда врезается в препятствие
    /// </summary>
    public ДействиеСнарядаПриПрепятствии действиеПриПрепятствии { get => _приПрепятствии; set => _приПрепятствии = value; }

    [SerializeField] Число _отскоковДоУничтожения = 3;
    /// <summary>
    /// Сколько раз снаряд может отскочить, прежде чем исчезнуть. 0 означает без ограничений
    /// </summary>
    public Число отскоковДоУничтожения { get => _отскоковДоУничтожения; set => _отскоковДоУничтожения = value; }

    [SerializeField] События _приПопадании;
    /// <summary>
    /// Срабатывает, когда снаряд попал в цель со Здоровьем
    /// </summary>
    public События приПопадании => _приПопадании;

    [SerializeField] События _приСтолкновенииСПрепятствием;
    /// <summary>
    /// Срабатывает, когда снаряд врезался в препятствие, что бы он после этого ни сделал
    /// </summary>
    public События приСтолкновенииСПрепятствием => _приСтолкновенииСПрепятствием;

    [SerializeField] События _приОтскоке;
    /// <summary>
    /// Срабатывает каждый раз, когда снаряд отскочил от препятствия
    /// </summary>
    public События приОтскоке => _приОтскоке;

    [SerializeField] События _приУничтожении;
    /// <summary>
    /// Срабатывает, когда снаряд исчезает после попадания или удара о препятствие
    /// </summary>
    public События приУничтожении => _приУничтожении;

    /// <summary>
    /// Куда летит снаряд. Если его не задали, то снаряд летит вдоль своей красной оси
    /// </summary>
    public Направление3D направление
    {
        get => _направление;
        set
        {
            _направление = ((Vector3)value).normalized;
            направлениеЗадано = да;
            ОбновитьФизику();
        }
    }
    Направление3D _направление;
    bool направлениеЗадано;

    /// <summary>
    /// Сколько раз снаряд уже отскочил
    /// </summary>
    public Число отскоков { get; private set; }

    /// <summary>
    /// Последний объект, в который врезался снаряд
    /// </summary>
    public GameObject последнийОбъект { get; private set; }

    GameObject владелец;
    ФизическоеТело2D тело2D;
    ФизическоеТело тело3D;
    bool уничтожен;

    void Awake()
    {
        ПоискОбъектов.ПеренестиТег(ref _тегЦелей, _тегиЦелей);
        TryGetComponent(out тело2D);
        TryGetComponent(out тело3D);
    }

    void Start()
    {
        if (!направлениеЗадано) направление = (Направление3D)transform.right;
        Удалить(gameObject, времяЖизни);
    }

    /// <summary>
    /// Запускает снаряд. Обычно это делает Атакер
    /// </summary>
    public void Запустить(Направление3D куда, Число сколькоУрона, Теги теги, GameObject кто)
    {
        урон = сколькоУрона;
        if (теги != null && !теги.любые) тегиЦелей = теги;
        владелец = кто;
        направление = куда;
    }

    void ОбновитьФизику()
    {
        if (тело2D != null) тело2D.движение = (Vector2)(Vector3)направление * скорость;
        if (тело3D != null) тело3D.движение = (Vector3)направление * скорость;
    }

    void Update()
    {
        if (тело2D == null && тело3D == null)
        {
            transform.position += (Vector3)направление * скорость * Время.времяСПрошлогоКадра;
        }
    }

    void Столкнулся(GameObject объект, bool нетвёрдый, Vector3 нормаль)
    {
        if (уничтожен) return;
        if (владелец != null && ПоискОбъектов.Свой(объект.transform, владелец.transform)) return;

        последнийОбъект = объект;
        Здоровье здоровье = объект.GetComponentInParent<Здоровье>();

        if (здоровье != null && _тегиЦелей.Подходит(объект))
        {
            здоровье.ПолучитьУрон(урон);
            _приПопадании.Вызвать();
            if (!пролетаетСквозьЦели) Уничтожить();
            return;
        }

        // Зоны вроде подбираемых монет не мешают полёту, если их явно не указали как препятствие
        bool препятствие = _тегиПрепятствий.любые ? !нетвёрдый && здоровье == null : _тегиПрепятствий.Подходит(объект);
        if (!препятствие) return;

        _приСтолкновенииСПрепятствием.Вызвать();

        switch (действиеПриПрепятствии)
        {
            case ДействиеСнарядаПриПрепятствии.Уничтожиться:
                Уничтожить();
                break;

            case ДействиеСнарядаПриПрепятствии.Отскочить:
                if (отскоковДоУничтожения > 0 && отскоков >= отскоковДоУничтожения)
                {
                    Уничтожить();
                    break;
                }
                отскоков++;
                Vector3 отражённое = Vector3.Reflect(направление, нормаль);
                направление = отражённое == Vector3.zero ? -(Vector3)направление : отражённое;
                ПовернутьПоНаправлению();
                _приОтскоке.Вызвать();
                break;
        }
    }

    void ПовернутьПоНаправлению()
    {
        Vector3 куда = направление;
        if (тело2D != null || Mathf.Approximately(куда.z, 0))
        {
            transform.rotation = Quaternion.Euler(0, 0, Mathf.Atan2(куда.y, куда.x) * Mathf.Rad2Deg);
        }
        else
        {
            transform.rotation = Quaternion.LookRotation(куда);
        }
    }

    void Уничтожить()
    {
        уничтожен = да;
        _приУничтожении.Вызвать();
        Удалить(gameObject);
    }

    // В нетвёрдом коллайдере нет точки касания, поэтому нормаль берётся от ближайшей точки поверхности
    Vector3 НормальК(Vector3 ближайшаяТочка)
    {
        Vector3 нормаль = transform.position - ближайшаяТочка;
        return нормаль.sqrMagnitude > 0.0001f ? нормаль.normalized : -(Vector3)направление;
    }

    void OnTriggerEnter2D(Collider2D collider) => Столкнулся(collider.gameObject, collider.isTrigger, НормальК(collider.ClosestPoint(transform.position)));
    void OnCollisionEnter2D(Collision2D collision) => Столкнулся(collision.gameObject, false, collision.GetContact(0).normal);
    void OnTriggerEnter(Collider other) => Столкнулся(other.gameObject, other.isTrigger, НормальК(other.ClosestPoint(transform.position)));
    void OnCollisionEnter(Collision collision) => Столкнулся(collision.gameObject, false, collision.GetContact(0).normal);
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(Снаряд))]
internal class СнарядEditor : RunityEditor<Снаряд>
{
    protected override void Отрисовать()
    {
        Текст("Этот объект летит вперёд и наносит урон при попадании. Ему нужен коллайдер, а чтобы столкновения срабатывали, у снаряда или у того, во что он врезается, должно быть физическое тело");

        Пробел();

        Поле("Скорость", x => x.скорость,
            (title, value) => EditorGUILayout.FloatField(title, value));

        Поле("Урон", x => x.урон,
            (title, value) => EditorGUILayout.IntField(title, value));

        Поле("Время жизни", x => x.времяЖизни,
            (title, value) => EditorGUILayout.FloatField(title, value));

        Пробел();

        ОтобразитьТеги("Теги целей", "_тегиЦелей");

        Поле("Пролетает сквозь цели", x => x.пролетаетСквозьЦели,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Пробел();

        ОтобразитьТеги("Теги препятствий", "_тегиПрепятствий");

        Поле("При препятствии", x => x.действиеПриПрепятствии,
            (title, value) => (ДействиеСнарядаПриПрепятствии)EditorGUILayout.EnumPopup(title, value));

        if (компонент.действиеПриПрепятствии == ДействиеСнарядаПриПрепятствии.Отскочить)
        {
            Поле("Отскоков до уничтожения", x => x.отскоковДоУничтожения,
                (title, value) => EditorGUILayout.IntField(title, value));
        }

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("При попадании", "_приПопадании");
        ОтобразитьСобытие("При столкновении с препятствием", "_приСтолкновенииСПрепятствием");
        if (компонент.действиеПриПрепятствии == ДействиеСнарядаПриПрепятствии.Отскочить)
        {
            ОтобразитьСобытие("При отскоке", "_приОтскоке");
        }
        ОтобразитьСобытие("При уничтожении", "_приУничтожении");
        ЗакончитьСобытия();
    }
}
#endif
