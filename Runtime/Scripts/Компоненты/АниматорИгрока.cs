using System;
#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;
using UnityEngine.Animations;
using UnityEngine.Playables;

/// <summary>
/// Что сейчас делает персонаж
/// </summary>
public enum СостояниеИгрока { Стоит, Идёт, Бежит, Прыгает, Падает, Приземляется, ПолучаетУрон, Атакует, Умирает }

/// <summary>
/// Какая анимация используется в состоянии
/// </summary>
public enum ВидАнимации { Гиф, Клип }

/// <summary>
/// Анимация для одного состояния: кадровая анимация Runity или обычный анимационный клип
/// </summary>
[Serializable]
public class АнимацияСостояния
{
    /// <summary>
    /// Гиф - работает кадровая анимация Runity. Клип - работает обычный анимационный клип
    /// </summary>
    public ВидАнимации вид;
    /// <summary>
    /// Кадровая анимация Runity
    /// </summary>
    public КадроваяАнимация кадры;
    /// <summary>
    /// Обычный анимационный клип Unity. Используется, если кадровая анимация не указана
    /// </summary>
    public AnimationClip клип;

    /// <summary>
    /// Даёт "да", если анимация указана
    /// </summary>
    public bool есть => вид == ВидАнимации.Гиф ? кадры != null : клип != null;

    /// <summary>
    /// Сколько секунд длится анимация
    /// </summary>
    public float длительность => !есть ? 0 : вид == ВидАнимации.Гиф ? кадры.количествоКадров / кадры.кадровВСекунду : клип.length;
}

/// <summary>
/// Сам переключает анимации персонажа: стоит, идёт, прыгает, падает, получает урон и другие. Нужно только разложить анимации по состояниям
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Анимация/Аниматор игрока")]
public class АниматорИгрока : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] АнимацияСостояния _стоит = new АнимацияСостояния();
    /// <summary>
    /// Когда персонаж стоит на месте
    /// </summary>
    public АнимацияСостояния стоит => _стоит;

    [SerializeField] АнимацияСостояния _идёт = new АнимацияСостояния();
    /// <summary>
    /// Когда персонаж идёт. Если нет отдельной анимации для ходьбы влево, эта отзеркаливается
    /// </summary>
    public АнимацияСостояния идёт => _идёт;

    [SerializeField] АнимацияСостояния _идётВлево = new АнимацияСостояния();
    /// <summary>
    /// Когда персонаж идёт влево. Необязательно
    /// </summary>
    public АнимацияСостояния идётВлево => _идётВлево;

    [SerializeField] АнимацияСостояния _идётВверх = new АнимацияСостояния();
    /// <summary>
    /// Для вида сверху: когда персонаж идёт вверх. Необязательно
    /// </summary>
    public АнимацияСостояния идётВверх => _идётВверх;

    [SerializeField] АнимацияСостояния _идётВниз = new АнимацияСостояния();
    /// <summary>
    /// Для вида сверху: когда персонаж идёт вниз. Необязательно
    /// </summary>
    public АнимацияСостояния идётВниз => _идётВниз;

    [SerializeField] АнимацияСостояния _бежит = new АнимацияСостояния();
    /// <summary>
    /// Когда персонаж бежит с компонентом Бег. Если не указать, будет ходьба
    /// </summary>
    public АнимацияСостояния бежит => _бежит;

    [SerializeField] АнимацияСостояния _прыгает = new АнимацияСостояния();
    /// <summary>
    /// Когда персонаж летит вверх после прыжка
    /// </summary>
    public АнимацияСостояния прыгает => _прыгает;

    [SerializeField] АнимацияСостояния _падает = new АнимацияСостояния();
    /// <summary>
    /// Когда персонаж падает вниз
    /// </summary>
    public АнимацияСостояния падает => _падает;

    [SerializeField] АнимацияСостояния _приземляется = new АнимацияСостояния();
    /// <summary>
    /// Проигрывается один раз, когда персонаж встал на землю
    /// </summary>
    public АнимацияСостояния приземляется => _приземляется;

    [SerializeField] АнимацияСостояния _получаетУрон = new АнимацияСостояния();
    /// <summary>
    /// Проигрывается один раз, когда Здоровье на этом объекте уменьшилось
    /// </summary>
    public АнимацияСостояния получаетУрон => _получаетУрон;

    [SerializeField] АнимацияСостояния _атакует = new АнимацияСостояния();
    /// <summary>
    /// Проигрывается один раз, когда Атакер или Луч на этом объекте атакует
    /// </summary>
    public АнимацияСостояния атакует => _атакует;

    [SerializeField] АнимацияСостояния _умирает = new АнимацияСостояния();
    /// <summary>
    /// Проигрывается, когда Здоровье закончилось. После неё другие анимации больше не включаются
    /// </summary>
    public АнимацияСостояния умирает => _умирает;

    [SerializeField] Флажок _отзеркаливать = да;
    /// <summary>
    /// Если "да", то при движении влево Спрайтер отзеркаливается, если для этого нет отдельной анимации
    /// </summary>
    public Флажок отзеркаливать { get => _отзеркаливать; set => _отзеркаливать = value; }

    [SerializeField] Дробное _порогСкорости = 0.1;
    /// <summary>
    /// С какой скорости персонаж считается идущим, а не стоящим
    /// </summary>
    public Дробное порогСкорости { get => _порогСкорости; set => _порогСкорости = value; }

    [SerializeField] События _приСменеСостояния;
    /// <summary>
    /// Срабатывает, когда персонаж начал делать что-то другое
    /// </summary>
    public События приСменеСостояния => _приСменеСостояния;

    /// <summary>
    /// Что персонаж делает сейчас
    /// </summary>
    public СостояниеИгрока состояние { get; private set; }

    АнимацияСостояния играет;
    СостояниеИгрока? разовое;
    float разовоеОсталось;
    bool умер;
    bool былНаЗемле = true;
    int прошлоеЗдоровье = int.MinValue;
    bool атакерБылГотов = true;
    bool лучБылГотов = true;
    Vector3 прошлоеМесто;

    PlayableGraph граф;
    AnimationPlayableOutput выход;
    AnimationClipPlayable клипСейчас;

    void Start() => прошлоеМесто = transform.position;

    // В первой версии вида не было: если в состоянии лежал только клип, переключаем его на Клип
    void OnValidate()
    {
        foreach (АнимацияСостояния анимация in new[] { _стоит, _идёт, _идётВлево, _идётВверх, _идётВниз, _бежит, _прыгает, _падает, _приземляется, _получаетУрон, _атакует, _умирает })
        {
            if (анимация != null && анимация.вид == ВидАнимации.Гиф && анимация.кадры == null && анимация.клип != null) анимация.вид = ВидАнимации.Клип;
        }
    }

    void OnDestroy()
    {
        if (граф.IsValid()) граф.Destroy();
    }

    void Update()
    {
        Vector3 скорость = Скорость();
        bool наЗемле = НаЗемле(скорость);
        bool видСверху = TryGetComponent(out Rigidbody2D тело2D) && тело2D.gravityScale == 0;

        ПроверитьРазовые(наЗемле);

        if (разовое.HasValue)
        {
            разовоеОсталось -= Время.времяСПрошлогоКадра;
            if (разовоеОсталось <= 0 && разовое != СостояниеИгрока.Умирает) разовое = null;
        }

        Vector3 поЗемле = видСверху ? new Vector3(скорость.x, скорость.y, 0) : new Vector3(скорость.x, 0, скорость.z);
        bool движется = поЗемле.magnitude > порогСкорости;

        СостояниеИгрока новое;
        if (разовое.HasValue) новое = разовое.Value;
        else if (!наЗемле && !видСверху) новое = скорость.y > 0 ? СостояниеИгрока.Прыгает : СостояниеИгрока.Падает;
        else if (движется) новое = TryGetComponent(out Бег _) && Управление.ускорениеУдерживается ? СостояниеИгрока.Бежит : СостояниеИгрока.Идёт;
        else новое = СостояниеИгрока.Стоит;

        bool смена = новое != состояние;
        состояние = новое;
        if (смена) _приСменеСостояния.Вызвать();

        АнимацияСостояния нужная = Анимация(новое, скорость, видСверху);
        bool свояАнимацияДляНаправления = нужная == _идётВлево || нужная == _идётВверх || нужная == _идётВниз;

        if (отзеркаливать && !свояАнимацияДляНаправления && Mathf.Abs(скорость.x) > порогСкорости && TryGetComponent(out SpriteRenderer спрайт))
        {
            спрайт.flipX = скорость.x < 0;
        }

        Включить(нужная, перезапустить: смена && разовое.HasValue);
        былНаЗемле = наЗемле;
    }

    void ПроверитьРазовые(bool наЗемле)
    {
        if (умер) return;

        if (TryGetComponent(out Здоровье здоровье))
        {
            int сейчас = здоровье.текущее;
            if (прошлоеЗдоровье != int.MinValue)
            {
                if (сейчас <= 0 && прошлоеЗдоровье > 0)
                {
                    умер = true;
                    Начать(СостояниеИгрока.Умирает, _умирает);
                    return;
                }
                if (сейчас < прошлоеЗдоровье) Начать(СостояниеИгрока.ПолучаетУрон, _получаетУрон);
            }
            прошлоеЗдоровье = сейчас;
        }

        if (TryGetComponent(out Атакер атакер))
        {
            if (атакерБылГотов && !атакер.готов) Начать(СостояниеИгрока.Атакует, _атакует);
            атакерБылГотов = атакер.готов;
        }

        if (TryGetComponent(out Луч луч))
        {
            if (лучБылГотов && !луч.готов) Начать(СостояниеИгрока.Атакует, _атакует);
            лучБылГотов = луч.готов;
        }

        if (наЗемле && !былНаЗемле) Начать(СостояниеИгрока.Приземляется, _приземляется);
    }

    // Если у состояния нет анимации, оно просто пропускается
    void Начать(СостояниеИгрока какое, АнимацияСостояния анимация)
    {
        if (!анимация.есть) return;
        if (разовое == СостояниеИгрока.Умирает) return;
        if (разовое.HasValue && Важность(разовое.Value) > Важность(какое)) return;

        разовое = какое;
        разовоеОсталось = анимация.длительность;
        играет = null;
    }

    static int Важность(СостояниеИгрока состояние) => состояние switch
    {
        СостояниеИгрока.Умирает => 4,
        СостояниеИгрока.ПолучаетУрон => 3,
        СостояниеИгрока.Атакует => 2,
        _ => 1
    };

    АнимацияСостояния Анимация(СостояниеИгрока какое, Vector3 скорость, bool видСверху)
    {
        switch (какое)
        {
            case СостояниеИгрока.Умирает: return _умирает;
            case СостояниеИгрока.ПолучаетУрон: return _получаетУрон;
            case СостояниеИгрока.Атакует: return _атакует;
            case СостояниеИгрока.Приземляется: return _приземляется;
            case СостояниеИгрока.Прыгает: return Первая(_прыгает, _падает, _стоит);
            case СостояниеИгрока.Падает: return Первая(_падает, _прыгает, _стоит);
            case СостояниеИгрока.Бежит:
                return _бежит.есть ? _бежит : Анимация(СостояниеИгрока.Идёт, скорость, видСверху);
            case СостояниеИгрока.Идёт:
                if (видСверху && Mathf.Abs(скорость.y) > Mathf.Abs(скорость.x))
                {
                    if (скорость.y > 0 && _идётВверх.есть) return _идётВверх;
                    if (скорость.y < 0 && _идётВниз.есть) return _идётВниз;
                }
                if (скорость.x < 0 && _идётВлево.есть) return _идётВлево;
                return Первая(_идёт, _стоит);
            default: return _стоит;
        }
    }

    static АнимацияСостояния Первая(params АнимацияСостояния[] варианты)
    {
        foreach (АнимацияСостояния вариант in варианты)
        {
            if (вариант.есть) return вариант;
        }
        return варианты[варианты.Length - 1];
    }

    void Включить(АнимацияСостояния анимация, bool перезапустить)
    {
        if (!анимация.есть) return;
        if (анимация == играет && !перезапустить) return;
        играет = анимация;

        if (анимация.вид == ВидАнимации.Гиф)
        {
            if (граф.IsValid()) выход.SetSourcePlayable(Playable.Null);

            if (!TryGetComponent(out ПроигрывательКадров проигрыватель))
            {
                проигрыватель = gameObject.AddComponent<ПроигрывательКадров>();
                проигрыватель.играетНаСтарте = нет;
            }
            проигрыватель.Запустить(анимация.кадры);
        }
        else
        {
            if (TryGetComponent(out ПроигрывательКадров проигрыватель)) проигрыватель.Приостановить();
            ИгратьКлип(анимация.клип);
        }
    }

    void ИгратьКлип(AnimationClip клип)
    {
        if (!граф.IsValid())
        {
            Animator аниматор = GetComponent<Animator>();
            if (аниматор == null) аниматор = gameObject.AddComponent<Animator>();

            граф = PlayableGraph.Create(name);
            выход = AnimationPlayableOutput.Create(граф, "Аниматор игрока", аниматор);
            граф.Play();
        }

        if (клипСейчас.IsValid()) клипСейчас.Destroy();
        клипСейчас = AnimationClipPlayable.Create(граф, клип);
        выход.SetSourcePlayable(клипСейчас);
    }

    Vector3 Скорость()
    {
        Vector3 результат;
        if (TryGetComponent(out Rigidbody2D тело2D)) результат = тело2D.linearVelocity;
        else if (TryGetComponent(out Rigidbody тело)) результат = тело.linearVelocity;
        else if (TryGetComponent(out CharacterController контроллер)) результат = контроллер.velocity;
        else результат = Время.времяСПрошлогоКадра > 0 ? (transform.position - прошлоеМесто) / Время.времяСПрошлогоКадра : Vector3.zero;

        прошлоеМесто = transform.position;
        return результат;
    }

    bool НаЗемле(Vector3 скорость)
    {
        if (TryGetComponent(out Персонаж персонаж)) return персонаж.наЗемле;
        if (TryGetComponent(out Прыжок прыжок)) return прыжок.чегоТоКасается;
        if (TryGetComponent(out Rigidbody2D тело2D) && тело2D.gravityScale == 0) return true;
        return Mathf.Abs(скорость.y) < 0.1f;
    }
}

#if UNITY_EDITOR
[CustomPropertyDrawer(typeof(АнимацияСостояния))]
internal class АнимацияСостоянияDrawer : PropertyDrawer
{
    public override void OnGUI(Rect position, SerializedProperty property, GUIContent label)
    {
        Rect поле = EditorGUI.PrefixLabel(position, label);

        SerializedProperty вид = property.FindPropertyRelative("вид");
        bool гиф = вид.enumValueIndex == (int)ВидАнимации.Гиф;

        Rect кнопка = new Rect(поле.x, поле.y, 42, поле.height);
        if (GUI.Button(кнопка, new GUIContent(гиф ? "Гиф" : "Клип", "Нажмите, чтобы переключить: кадровая анимация Runity или обычный анимационный клип"), EditorStyles.miniButton))
        {
            вид.enumValueIndex = гиф ? (int)ВидАнимации.Клип : (int)ВидАнимации.Гиф;
            гиф = !гиф;
        }

        Rect объект = new Rect(поле.x + 46, поле.y, поле.width - 46, поле.height);
        EditorGUI.PropertyField(объект, property.FindPropertyRelative(гиф ? "кадры" : "клип"), GUIContent.none);
    }
}

