        ОтобразитьСвойство("Идёт влево", "_идётВлево");
        ОтобразитьСвойство("Идёт вверх", "_идётВверх");
        ОтобразитьСвойство("Идёт вниз", "_идётВниз");
        ОтобразитьСвойство("Бежит", "_бежит");
        Пробел();
        ОтобразитьСвойство("Прыгает", "_прыгает");
        ОтобразитьСвойство("Падает", "_падает");
        ОтобразитьСвойство("Приземляется", "_приземляется");
