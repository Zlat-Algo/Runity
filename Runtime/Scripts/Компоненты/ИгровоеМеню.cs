#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;

/// <summary>
/// Пауза по Escape и экраны поражения и победы. Останавливает время, показывает курсор и умеет переходить между сценами.
/// Панели - это Группы интерфейса: меню показывает и прячет их само
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Интерфейс/ Основа/Игровое меню")]
public class ИгровоеМеню : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] ГруппаИнтерфейса _пауза;
    /// <summary>
    /// Панель паузы. Появляется и прячется по клавише Escape. Если пусто, паузы нет
    /// </summary>
    public ГруппаИнтерфейса пауза { get => _пауза; set => _пауза = value; }

    [SerializeField] ГруппаИнтерфейса _поражение;
    /// <summary>
    /// Панель, которая появляется при поражении
    /// </summary>
    public ГруппаИнтерфейса поражение { get => _поражение; set => _поражение = value; }

    [SerializeField] ГруппаИнтерфейса _победа;
    /// <summary>
    /// Панель, которая появляется при победе
    /// </summary>
    public ГруппаИнтерфейса победа { get => _победа; set => _победа = value; }

    [SerializeField] Строка _сценаМеню = "Меню";
    /// <summary>
    /// Имя сцены главного меню. Туда ведёт «В меню»
    /// </summary>
    public Строка сценаМеню { get => _сценаМеню; set => _сценаМеню = value; }

    [SerializeField] События _приПаузе;
    /// <summary>
    /// Срабатывает, когда игра поставлена на паузу
    /// </summary>
    public События приПаузе => _приПаузе;

    [SerializeField] События _приПродолжении;
    /// <summary>
    /// Срабатывает, когда пауза снята
    /// </summary>
    public События приПродолжении => _приПродолжении;

    [SerializeField] События _приПоражении;
    /// <summary>
    /// Срабатывает при поражении
    /// </summary>
    public События приПоражении => _приПоражении;

    [SerializeField] События _приПобеде;
    /// <summary>
    /// Срабатывает при победе
    /// </summary>
    public События приПобеде => _приПобеде;

    /// <summary>
    /// Даёт "да", пока игра остановлена паузой, поражением или победой
    /// </summary>
    public Флажок остановлена { get; private set; }

    /// <summary>
    /// Даёт "да" после поражения или победы
    /// </summary>
    public Флажок играОкончена { get; private set; }

    void Start()
    {
        Время.скоростьИгры = 1;
        foreach (ГруппаИнтерфейса панель in new[] { пауза, поражение, победа })
            if (панель != null) панель.Спрятать();
        // В меню нужен курсор, а в игре от первого лица - нет
        Мышка.режим = FindAnyObjectByType<ОбзорМышкой>() != null ? РежимМышки.Отключенная : РежимМышки.Свободная;
    }

    void Update()
    {
        if (!Управление.выходНажат || играОкончена || пауза == null) return;
        if (ОкноДиалога.главное != null && ОкноДиалога.главное.идётРазговор) return;
        if (остановлена) Продолжить();
        else Пауза();
    }

    void Остановить(ГруппаИнтерфейса панель)
    {
        остановлена = да;
        Время.скоростьИгры = 0;
        Мышка.режим = РежимМышки.Свободная;
        if (панель != null) панель.ПлавноПоказать();
    }

    /// <summary>
    /// Останавливает игру и показывает меню паузы
    /// </summary>
    public void Пауза()
    {
        if (играОкончена || остановлена) return;
        Остановить(пауза);
        _приПаузе.Вызвать();
    }

    /// <summary>
    /// Убирает паузу
    /// </summary>
    public void Продолжить()
    {
        if (играОкончена || !остановлена) return;
        остановлена = нет;
        Время.скоростьИгры = 1;
        if (FindAnyObjectByType<ОбзорМышкой>() != null) Мышка.режим = РежимМышки.Отключенная;
        if (пауза != null) пауза.Спрятать();
        _приПродолжении.Вызвать();
    }

    /// <summary>
    /// Останавливает игру и показывает экран поражения
    /// </summary>
    public void Проиграть()
    {
        if (играОкончена) return;
        if (пауза != null) пауза.Спрятать();
        играОкончена = да;
        Остановить(поражение);
        _приПоражении.Вызвать();
    }

    /// <summary>
    /// Останавливает игру и показывает экран победы
    /// </summary>
    public void Победить()
    {
        if (играОкончена) return;
        if (пауза != null) пауза.Спрятать();
        играОкончена = да;
        Остановить(победа);
        _приПобеде.Вызвать();
    }

    /// <summary>
    /// Начинает текущую сцену заново
    /// </summary>
    public void Заново()
    {
        Время.скоростьИгры = 1;
        Сцены.Перезапустить();
    }

    /// <summary>
    /// Запускает сцену по имени. Если есть Экран загрузки, переход идёт через него
    /// </summary>
    public void Перейти(Строка имяСцены)
    {
        Время.скоростьИгры = 1;
        Сцены.Запустить(имяСцены);
    }

    /// <summary>
    /// Возвращает в главное меню
    /// </summary>
    public void ВМеню() => Перейти(сценаМеню);

    /// <summary>
    /// Закрывает игру. В редакторе останавливает её
    /// </summary>
    public void Выйти()
    {
#if UNITY_EDITOR
        EditorApplication.isPlaying = false;
#else
        Application.Quit();
#endif
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(ИгровоеМеню))]
internal class ИгровоеМенюEditor : RunityEditor<ИгровоеМеню>
{
    protected override void Отрисовать()
    {
        Текст("Пауза по Escape, экраны поражения и победы и переходы между сценами. Вызывайте Проиграть и Победить из событий, например «Когда закончилось здоровье»");

        Пробел();

        Поле("Пауза", x => x.пауза, (title, value) => ПолеОбъекта<ГруппаИнтерфейса>(title, value, true));
        Поле("Поражение", x => x.поражение, (title, value) => ПолеОбъекта<ГруппаИнтерфейса>(title, value, true));
        Поле("Победа", x => x.победа, (title, value) => ПолеОбъекта<ГруппаИнтерфейса>(title, value, true));
        Поле("Сцена меню", x => x.сценаМеню, (title, value) => EditorGUILayout.TextField(title, value));

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("При паузе", "_приПаузе");
        ОтобразитьСобытие("При продолжении", "_приПродолжении");
        ОтобразитьСобытие("При поражении", "_приПоражении");
        ОтобразитьСобытие("При победе", "_приПобеде");
        ЗакончитьСобытия();
    }
}
#endif
