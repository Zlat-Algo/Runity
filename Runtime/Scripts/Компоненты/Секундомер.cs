using System.Collections.Generic;
#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// Считает, сколько прошло времени: время прохождения уровня, забега, круга. Запоминает лучшее время и круги
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Механики/Секундомер")]
public class Секундомер : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] Флажок _запускатьНаСтарте = да;
    /// <summary>
    /// Если "да", секундомер начинает считать сразу при запуске сцены
    /// </summary>
    public Флажок запускатьНаСтарте { get => _запускатьНаСтарте; set => _запускатьНаСтарте = value; }

    [SerializeField] Флажок _учитыватьСкоростьВремени = да;
    /// <summary>
    /// Если "да", на паузе (когда время остановлено) секундомер тоже стоит
    /// </summary>
    public Флажок учитыватьСкоростьВремени { get => _учитыватьСкоростьВремени; set => _учитыватьСкоростьВремени = value; }

    [SerializeField] Graphic _текст;
    /// <summary>
    /// Текст, в котором показывается время. Если пусто, берётся текст с этого же объекта
    /// </summary>
    public Graphic текст { get => _текст; set => _текст = value; }

    [SerializeField] ФорматВремени _формат = ФорматВремени.МинутыИСекунды;
    /// <summary>
    /// Как писать время: секундами, минутами и секундами или часами, минутами и секундами
    /// </summary>
    public ФорматВремени формат { get => _формат; set => _формат = value; }

    [SerializeField] int _знаковПослеЗапятой = 2;
    /// <summary>
    /// Сколько знаков показывать после запятой у секунд
    /// </summary>
    public Число знаковПослеЗапятой { get => _знаковПослеЗапятой; set => _знаковПослеЗапятой = value; }

    [SerializeField] Строка _текстДо = "";
    /// <summary>
    /// Что писать перед временем, например «Время: »
    /// </summary>
    public Строка текстДо { get => _текстДо; set => _текстДо = value; }

    [SerializeField] Строка _сохранятьЛучшееПодИменем = "";
    /// <summary>
    /// Если указать имя, лучшее (самое маленькое) время запоминается между запусками игры
    /// </summary>
    public Строка сохранятьЛучшееПодИменем { get => _сохранятьЛучшееПодИменем; set => _сохранятьЛучшееПодИменем = value; }

    [SerializeField] События _приЗапуске;
    /// <summary>
    /// Срабатывает, когда секундомер запущен
    /// </summary>
    public События приЗапуске => _приЗапуске;

    [SerializeField] События _приОстановке;
    /// <summary>
    /// Срабатывает, когда секундомер остановлен
    /// </summary>
    public События приОстановке => _приОстановке;

    [SerializeField] События _приНовомРекорде;
    /// <summary>
    /// Срабатывает при остановке, если это время лучше прежнего
    /// </summary>
    public События приНовомРекорде => _приНовомРекорде;

    [SerializeField] События _приКруге;
    /// <summary>
    /// Срабатывает, когда отмечен круг
    /// </summary>
    public События приКруге => _приКруге;

    /// <summary>
    /// Сколько секунд прошло
    /// </summary>
    public Дробное прошло { get; private set; }

    /// <summary>
    /// Даёт "да", пока секундомер считает
    /// </summary>
    public Флажок идёт { get; private set; }

    /// <summary>
    /// Лучшее время. 0 - его ещё нет
    /// </summary>
    public Дробное лучшее { get; private set; }

    /// <summary>
    /// Время каждого отмеченного круга, в секундах
    /// </summary>
    public List<float> круги { get; } = new List<float>();

    /// <summary>
    /// Прошедшее время в виде текста, например «01:23,45»
    /// </summary>
    public Строка текстВремени => (string)текстДо + ЗаписьТекста.Время(прошло, формат, знаковПослеЗапятой, false, false);

    float начатКруг;

    void Start()
    {
        if (текст == null) _текст = ЗаписьТекста.НайтиРядом(this);
        if (!string.IsNullOrEmpty(сохранятьЛучшееПодИменем)) лучшее = Сохранения.ЗагрузитьДробное(сохранятьЛучшееПодИменем, 0);
        if (запускатьНаСтарте) Запустить();
        ОбновитьТекст();
    }

    void Update()
    {
        if (!идёт) return;
        прошло = (float)прошло + (учитыватьСкоростьВремени ? Time.deltaTime : Time.unscaledDeltaTime);
        ОбновитьТекст();
    }

    void ОбновитьТекст()
    {
        if (текст != null) ЗаписьТекста.Записать(текст, текстВремени);
    }

    /// <summary>
    /// Начинает отсчёт с нуля
    /// </summary>
    public void Запустить()
    {
        прошло = 0;
        начатКруг = 0;
        круги.Clear();
        идёт = да;
        ОбновитьТекст();
        _приЗапуске.Вызвать();
    }

    /// <summary>
    /// Останавливает отсчёт и проверяет, не рекорд ли это
    /// </summary>
    public void Остановить()
    {
        if (!идёт) return;
        идёт = нет;
        ОбновитьТекст();
        _приОстановке.Вызвать();

        if ((float)лучшее <= 0 || (float)прошло < (float)лучшее)
        {
            лучшее = прошло;
            if (!string.IsNullOrEmpty(сохранятьЛучшееПодИменем)) Сохранения.СохранитьДробное(сохранятьЛучшееПодИменем, лучшее);
            _приНовомРекорде.Вызвать();
        }
    }

    /// <summary>
    /// Ставит отсчёт на паузу, не сбрасывая время
    /// </summary>
    public void Приостановить() => идёт = нет;

    /// <summary>
    /// Продолжает отсчёт после паузы
    /// </summary>
    public void Продолжить() => идёт = да;

    /// <summary>
    /// Сбрасывает время на ноль и останавливает отсчёт
    /// </summary>
    public void Сбросить()
    {
        идёт = нет;
        прошло = 0;
        круги.Clear();
        ОбновитьТекст();
    }

    /// <summary>
    /// Отмечает круг: запоминает, сколько длился круг с прошлой отметки
    /// </summary>
    public void Круг()
    {
        круги.Add((float)прошло - начатКруг);
        начатКруг = прошло;
        _приКруге.Вызвать();
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(Секундомер))]
internal class СекундомерEditor : RunityEditor<Секундомер>
{
    public override bool RequiresConstantRepaint() => Application.isPlaying;

    protected override void Отрисовать()
    {
        Текст(Application.isPlaying ? $"Прошло: {(string)компонент.текстВремени}" : "Этот объект считает, сколько прошло времени, и запоминает лучшее время");

        Пробел();

        Поле("Запускать на старте", x => x.запускатьНаСтарте, (title, value) => EditorGUILayout.Toggle(title, value));
        Поле("Учитывать скорость времени", x => x.учитыватьСкоростьВремени, (title, value) => EditorGUILayout.Toggle(title, value));

        Пробел();

        Поле("Текст", x => x.текст, (title, value) => ПолеОбъекта<Graphic>(title, value, true));
        Поле("Формат", x => x.формат, (title, value) => (ФорматВремени)EditorGUILayout.EnumPopup(title, value));
        Поле("Знаков после запятой", x => x.знаковПослеЗапятой, (title, value) => EditorGUILayout.IntSlider(title, value, 0, 3));
        Поле("Текст до", x => x.текстДо, (title, value) => EditorGUILayout.TextField(title, value));
        Поле("Сохранять лучшее под именем", x => x.сохранятьЛучшееПодИменем, (title, value) => EditorGUILayout.TextField(title, value));

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("При запуске", "_приЗапуске");
        ОтобразитьСобытие("При остановке", "_приОстановке");
        ОтобразитьСобытие("При новом рекорде", "_приНовомРекорде");
        ОтобразитьСобытие("При круге", "_приКруге");
        ЗакончитьСобытия();
    }
}
#endif
