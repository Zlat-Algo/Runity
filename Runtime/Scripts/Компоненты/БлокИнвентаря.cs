#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;

/// <summary>
/// Сетка из Ячеек инвентаря: рюкзак, сундук, панель быстрого доступа. Размер ячеек и расстояние между ними задаются в Группе элементов
/// </summary>
[DisallowMultipleComponent]
[RequireComponent(typeof(RectTransform), typeof(ГруппаЭлементов))]
[AddComponentMenu("  Runity/ Механики/ Инвентарь/Блок инвентаря")]
public class БлокИнвентаря : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] Инвентарь _инвентарь;
    /// <summary>
    /// Какой инвентарь показывает блок. Если не указать, найдётся первый инвентарь на сцене
    /// </summary>
    public Инвентарь инвентарь { get => _инвентарь; set => _инвентарь = value; }

    [SerializeField] Число _количествоЯчеек = 9;
    /// <summary>
    /// Сколько ячеек в блоке
    /// </summary>
    public Число количествоЯчеек { get => _количествоЯчеек; set => _количествоЯчеек = Mathf.Max(1, value); }

    [SerializeField] Число _первыйНомер = 0;
    /// <summary>
    /// С какого номера ячейки инвентаря начинается блок. Так один инвентарь можно разделить на панель и рюкзак
    /// </summary>
    public Число первыйНомер { get => _первыйНомер; set => _первыйНомер = Mathf.Max(0, value); }

    [SerializeField] ЯчейкаИнвентаря _образец;
    /// <summary>
    /// Ячейка, копии которой заполняют блок. Если не указать, будут ячейки стандартного вида
    /// </summary>
    public ЯчейкаИнвентаря образец { get => _образец; set => _образец = value; }

    [SerializeField] Флажок _ограничитьИнвентарь = да;
    /// <summary>
    /// Если "да", то в инвентаре станет столько ячеек, сколько их в блоке, и лишнее туда не поместится
    /// </summary>
    public Флажок ограничитьИнвентарь { get => _ограничитьИнвентарь; set => _ограничитьИнвентарь = value; }

    /// <summary>
    /// Все ячейки блока по порядку
    /// </summary>
    public ЯчейкаИнвентаря[] ячейки => GetComponentsInChildren<ЯчейкаИнвентаря>(true);

    void Start()
    {
        if (инвентарь == null) инвентарь = FindAnyObjectByType<Инвентарь>();
        if (ячейки.Length != количествоЯчеек) Перестроить();
        else Настроить();
    }

    /// <summary>
    /// Удаляет старые ячейки и создаёт новые по настройкам блока
    /// </summary>
    public void Перестроить()
    {
        foreach (ЯчейкаИнвентаря старая in ячейки)
        {
            if (старая == образец) continue;
            if (Application.isPlaying) Destroy(старая.gameObject);
            else DestroyImmediate(старая.gameObject);
        }

        for (int i = 0; i < количествоЯчеек; i++)
        {
            ЯчейкаИнвентаря ячейка = образец != null
                ? Instantiate(образец, transform)
                : ЯчейкаИнвентаря.СоздатьСтандартную(transform, ФонЯчейки());
            ячейка.gameObject.SetActive(true);
            ячейка.name = $"Ячейка {i + 1}";
        }

        Настроить();
    }

    void Reset()
    {
#if UNITY_EDITOR
        // Группа элементов добавляется вместе с блоком, а менять её во время добавления Unity не разрешает
        EditorApplication.delayCall += () =>
        {
            if (this != null) СделатьСетку();
        };
#endif
    }

    // Блоку нужна сетка. Если группа ещё не сетка, ставим ей удобные настройки один раз, дальше их можно менять в Группе элементов
    ГруппаЭлементов СделатьСетку()
    {
        ГруппаЭлементов группа = GetComponent<ГруппаЭлементов>();
        if (группа.оригинал != null && группа.режим == РежимГруппы.Сеткой) return группа;

        группа.режим = РежимГруппы.Сеткой;
        группа.столбцов = 9;
        группа.размерКлетки = new Vector2(80, 80);
        группа.отступМежду = 8;
        return группа;
    }

    void Настроить()
    {
        ГруппаЭлементов группа = СделатьСетку();

        int номер = первыйНомер;
        foreach (ЯчейкаИнвентаря ячейка in ячейки)
        {
            if (ячейка == образец && !ячейка.gameObject.activeSelf) continue;
            ячейка.инвентарь = инвентарь;
            ячейка.показывает = ЧтоПоказываетЯчейка.ЯчейкуПоНомеру;
            ячейка.номер = номер++;
        }

        if (ограничитьИнвентарь && инвентарь != null && инвентарь.количествоЯчеек < (int)первыйНомер + (int)количествоЯчеек)
        {
            инвентарь.количествоЯчеек = (int)первыйНомер + (int)количествоЯчеек;
        }

        // Размер блока подгоняется под ячейки, если в группе задано число столбцов
        int столбцов = (int)группа.столбцов;
        if (столбцов <= 0) return;
        Vector2 клетка = группа.размерКлетки;
        float отступ = группа.отступМежду;
        int строк = Mathf.CeilToInt((float)количествоЯчеек / столбцов);
        int вСтроке = Mathf.Min(столбцов, количествоЯчеек);
        ((RectTransform)transform).sizeDelta = new Vector2(вСтроке * клетка.x + (вСтроке - 1) * отступ + 2 * (int)группа.поля, строк * клетка.y + (строк - 1) * отступ + 2 * (int)группа.поля);
    }

    Sprite ФонЯчейки()
    {
#if UNITY_EDITOR
        return AssetDatabase.GetBuiltinExtraResource<Sprite>("UI/Skin/UISprite.psd");
#else
        return null;
#endif
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(БлокИнвентаря))]
internal class БлокИнвентаряEditor : RunityEditor<БлокИнвентаря>
{
    protected override void Отрисовать()
    {
        Текст("Этот объект показывает часть инвентаря сеткой ячеек. Вещи заполняют ячейки по очереди. Размер ячеек и число столбцов меняются в Группе элементов, а после смены количества ячеек нажмите «Перестроить ячейки»");

        Пробел();

        Поле("Инвентарь", x => x.инвентарь,
            (title, value) => ПолеОбъекта<Инвентарь>(title, value, true));

        Поле("Количество ячеек", x => x.количествоЯчеек,
            (title, value) => EditorGUILayout.IntField(title, value));

        Поле("Первый номер", x => x.первыйНомер,
            (title, value) => EditorGUILayout.IntField(title, value));

        Поле("Образец", x => x.образец,
            (title, value) => ПолеОбъекта<ЯчейкаИнвентаря>(title, value, true));

        Поле("Ограничить инвентарь", x => x.ограничитьИнвентарь,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Пробел();

        Кнопка("Перестроить ячейки", x => x.Перестроить());
    }
}
#endif
