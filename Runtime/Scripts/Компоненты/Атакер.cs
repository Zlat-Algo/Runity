#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;

/// <summary>
/// Как объект наносит урон
/// </summary>
public enum РежимАтаки { Ближняя, Снарядами }

/// <summary>
/// На какую кнопку объект атакует
/// </summary>
public enum КнопкаАтаки { ЛКМ, ПКМ, Пробел, Использовать, ТолькоИзКодаИСобытий }

/// <summary>
/// Куда летит снаряд
/// </summary>
public enum КудаАтаковать { КудаСмотрит, НаМышку, НаЗамеченного }

/// <summary>
/// Наносит урон компоненту Здоровье у других объектов: вблизи или снарядами
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("  Runity/ Механики/ Бой/Атакер")]
public class Атакер : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] РежимАтаки _режим;
    /// <summary>
    /// Бьёт вблизи или стреляет снарядами
    /// </summary>
    public РежимАтаки режим { get => _режим; set => _режим = value; }

    [SerializeField] КнопкаАтаки _кнопка;
    /// <summary>
    /// На какую кнопку игрок атакует
    /// </summary>
    public КнопкаАтаки кнопка { get => _кнопка; set => _кнопка = value; }

    [SerializeField] Флажок _атаковатьПриУдержании = нет;
    /// <summary>
    /// Если "да", то можно не нажимать кнопку каждый раз, а просто держать её
    /// </summary>
    public Флажок атаковатьПриУдержании { get => _атаковатьПриУдержании; set => _атаковатьПриУдержании = value; }

    [SerializeField] Флажок _атаковатьЗамеченных = нет;
    /// <summary>
    /// Если "да", то объект сам атакует, пока его Поле зрения кого-то видит. Подходит для врагов
    /// </summary>
    public Флажок атаковатьЗамеченных { get => _атаковатьЗамеченных; set => _атаковатьЗамеченных = value; }

    [SerializeField] Флажок _режим2D = да;
    /// <summary>
    /// "Да" для 2D-игр
    /// </summary>
    public Флажок режим2D { get => _режим2D; set => _режим2D = value; }

    [SerializeField] Число _урон = 1;
    /// <summary>
    /// Сколько здоровья отнимает одна атака
    /// </summary>
    public Число урон { get => _урон; set => _урон = value; }

    [SerializeField] Дробное _перезарядка = 0.5;
    /// <summary>
    /// Сколько секунд нужно ждать между атаками
    /// </summary>
    public Дробное перезарядка { get => _перезарядка; set => _перезарядка = value; }

    [SerializeField, HideInInspector] Строка _тегЦелей;

    [SerializeField] Теги _тегиЦелей = new Теги();
    /// <summary>
    /// Атакует только объекты с этими тегами. Если теги не выбраны, то любые объекты со Здоровьем
    /// </summary>
    public Теги тегиЦелей => _тегиЦелей;

    [SerializeField] Дробное _дальность = 1.5;
    /// <summary>
    /// Как далеко достаёт ближняя атака
    /// </summary>
    public Дробное дальность { get => _дальность; set => _дальность = value; }

    [SerializeField] Дробное _уголУдара = 120;
    /// <summary>
    /// Ширина удара в градусах. 360 означает удар вокруг себя
    /// </summary>
    public Дробное уголУдара { get => _уголУдара; set => _уголУдара = value; }

    [SerializeField] НаправлениеВзгляда2D _взгляд2D;
    /// <summary>
    /// Куда смотрит объект в 2D, если его не поворачивали
    /// </summary>
    public НаправлениеВзгляда2D взгляд2D { get => _взгляд2D; set => _взгляд2D = value; }

    [SerializeField] GameObject _снаряд;
    /// <summary>
    /// Префаб снаряда. Если в нём есть компонент Снаряд, то он получит урон и направление от Атакера
    /// </summary>
    public GameObject снаряд { get => _снаряд; set => _снаряд = value; }

    [SerializeField] Transform _точкаВылета;
    /// <summary>
    /// Откуда вылетает снаряд. Если не указать, то из центра объекта
    /// </summary>
    public Transform точкаВылета { get => _точкаВылета; set => _точкаВылета = value; }

    [SerializeField] КудаАтаковать _кудаСтрелять;
    /// <summary>
    /// В какую сторону летят снаряды
    /// </summary>
    public КудаАтаковать кудаСтрелять { get => _кудаСтрелять; set => _кудаСтрелять = value; }

    [SerializeField] События _приАтаке;
    /// <summary>
    /// Срабатывает при каждой атаке, даже если она никого не задела
    /// </summary>
    public События приАтаке => _приАтаке;

    [SerializeField] События _приПопадании;
    /// <summary>
    /// Срабатывает для каждого объекта, задетого ближней атакой
    /// </summary>
    public События приПопадании => _приПопадании;

    [SerializeField] События _приПромахе;
    /// <summary>
    /// Срабатывает, если ближняя атака никого не задела
    /// </summary>
    public События приПромахе => _приПромахе;

    [SerializeField] События _приПерезарядке;
    /// <summary>
    /// Срабатывает, когда можно атаковать снова
    /// </summary>
    public События приПерезарядке => _приПерезарядке;

    /// <summary>
    /// Даёт "да", если перезарядка закончилась
    /// </summary>
    public Флажок готов => перезарядкаОсталось <= 0;

    /// <summary>
    /// Последний объект, которого задела атака
    /// </summary>
    public GameObject последняяЦель { get; private set; }

    float перезарядкаОсталось;
    ПолеЗрения полеЗрения;

    void Awake()
    {
        ПоискОбъектов.ПеренестиТег(ref _тегЦелей, _тегиЦелей);
        TryGetComponent(out полеЗрения);
    }

    Флажок КнопкаНажата() => кнопка switch
    {
        КнопкаАтаки.ЛКМ => атаковатьПриУдержании ? Управление.ЛКМУдерживается : Управление.ЛКМНажата,
        КнопкаАтаки.ПКМ => атаковатьПриУдержании ? Управление.ПКМУдерживается : Управление.ПКМНажата,
        КнопкаАтаки.Пробел => атаковатьПриУдержании ? Управление.пробелУдерживается : Управление.пробелНажат,
        КнопкаАтаки.Использовать => атаковатьПриУдержании ? Управление.использоватьУдерживается : Управление.использоватьНажато,
        _ => нет
    };

    void Update()
    {
        if (перезарядкаОсталось > 0)
        {
            перезарядкаОсталось -= Время.времяСПрошлогоКадра;
            if (перезарядкаОсталось <= 0)
            {
                _приПерезарядке.Вызвать();
            }
        }

        bool вижуЦель = атаковатьЗамеченных && полеЗрения != null && полеЗрения.ктоТоВиден;

        if (КнопкаНажата() || вижуЦель)
        {
            Атаковать();
        }
    }

    /// <summary>
    /// Атакует прямо сейчас, если закончилась перезарядка
    /// </summary>
    public void Атаковать()
    {
        if (!готов) return;

        перезарядкаОсталось = перезарядка;
        _приАтаке.Вызвать();

        if (режим == РежимАтаки.Ближняя)
        {
            Ударить();
        }
        else
        {
            Выстрелить();
        }
    }

    void Ударить()
    {
        Vector3 взгляд = ПоискОбъектов.Взгляд(transform, режим2D, взгляд2D, да);
        bool попал = нет;

        foreach (GameObject объект in ПоискОбъектов.ВРадиусе(transform.position, дальность, режим2D))
        {
            if (ПоискОбъектов.Свой(объект.transform, transform)) continue;
            if (!_тегиЦелей.Подходит(объект)) continue;
            if (!ПоискОбъектов.ВСекторе(transform.position, взгляд, объект.transform.position, уголУдара, режим2D)) continue;

            Здоровье здоровье = объект.GetComponentInParent<Здоровье>();
            if (здоровье == null) continue;

            попал = да;
            последняяЦель = объект;
            здоровье.ПолучитьУрон(урон);
            _приПопадании.Вызвать();
        }

        if (!попал)
        {
            _приПромахе.Вызвать();
        }
    }

    void Выстрелить()
    {
        if (снаряд == null)
        {
            Консоль.НапечататьОшибку("Атакеру не указан снаряд", this);
            return;
        }

        Vector3 откуда = точкаВылета != null ? точкаВылета.position : transform.position;
        Vector3 направление = НаправлениеВыстрела(откуда);

        GameObject копия = Instantiate(снаряд, откуда, ПоворотПоНаправлению(направление));

        if (копия.TryGetComponent(out Снаряд компонентСнаряда))
        {
            компонентСнаряда.Запустить(направление, урон, _тегиЦелей, gameObject);
        }
    }

    Vector3 НаправлениеВыстрела(Vector3 откуда)
    {
        Vector3 взгляд = ПоискОбъектов.Взгляд(transform, режим2D, взгляд2D, да);

        switch (кудаСтрелять)
        {
            case КудаАтаковать.НаМышку:
                Vector3 мышка = Мышка.позицияВМире2D;
                мышка.z = откуда.z;
                return (мышка - откуда).normalized;

            case КудаАтаковать.НаЗамеченного:
                if (полеЗрения != null && полеЗрения.ближайший != null)
                {
                    return (полеЗрения.ближайший.transform.position - откуда).normalized;
                }
                return взгляд;

            default:
                return взгляд;
        }
    }

    Quaternion ПоворотПоНаправлению(Vector3 направление)
    {
        if (режим2D)
        {
            return Quaternion.Euler(0, 0, Mathf.Atan2(направление.y, направление.x) * Mathf.Rad2Deg);
        }
        return Quaternion.LookRotation(направление);
    }

    void OnDrawGizmosSelected()
    {
        if (режим != РежимАтаки.Ближняя) return;

        Gizmos.color = Color.red;
        Gizmos.DrawWireSphere(transform.position, дальность);
    }
}

#if UNITY_EDITOR
[CanEditMultipleObjects]
[CustomEditor(typeof(Атакер))]
internal class АтакерEditor : RunityEditor<Атакер>
{
    protected override void Отрисовать()
    {
        Текст("Этот объект наносит урон всем, у кого есть компонент Здоровье и коллайдер");

        Пробел();

        ПредупреждениеПроУправление();

        Поле("Режим", x => x.режим,
            (title, value) => (РежимАтаки)EditorGUILayout.EnumPopup(title, value));

        Поле("Режим 2D", x => x.режим2D,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Пробел();

        Поле("Кнопка", x => x.кнопка,
            (title, value) => (КнопкаАтаки)EditorGUILayout.EnumPopup(title, value));

        Поле("Атаковать при удержании", x => x.атаковатьПриУдержании,
            (title, value) => EditorGUILayout.Toggle(title, value));

        Поле("Атаковать замеченных", x => x.атаковатьЗамеченных,
            (title, value) => EditorGUILayout.Toggle(title, value));

        if (компонент.атаковатьЗамеченных && !компонент.TryGetComponent(out ПолеЗрения _))
        {
            Текст("Добавьте этому объекту Поле зрения", MessageType.Warning);
        }

        Пробел();

        Поле("Урон", x => x.урон,
            (title, value) => EditorGUILayout.IntField(title, value));

        Поле("Перезарядка", x => x.перезарядка,
            (title, value) => EditorGUILayout.FloatField(title, value));

        ОтобразитьТеги("Теги целей", "_тегиЦелей");

        Пробел();

        if (компонент.режим == РежимАтаки.Ближняя)
        {
            Поле("Дальность", x => x.дальность,
                (title, value) => EditorGUILayout.FloatField(title, value));

            Поле("Угол удара", x => x.уголУдара,
                (title, value) => EditorGUILayout.Slider(title, value, 1, 360));
        }
        else
        {
            Поле("Снаряд", x => x.снаряд,
                (title, value) => ПолеОбъекта<GameObject>(title, value));

            Поле("Точка вылета", x => x.точкаВылета,
                (title, value) => ПолеОбъекта<Transform>(title, value, true));

            Поле("Куда стрелять", x => x.кудаСтрелять,
                (title, value) => (КудаАтаковать)EditorGUILayout.EnumPopup(title, value));
        }

        if (компонент.режим2D)
        {
            Поле("Куда смотрит", x => x.взгляд2D,
                (title, value) => (НаправлениеВзгляда2D)EditorGUILayout.EnumPopup(title, value));
        }

        Пробел();

        НачатьСобытия();
        ОтобразитьСобытие("При атаке", "_приАтаке");
        if (компонент.режим == РежимАтаки.Ближняя)
        {
            ОтобразитьСобытие("При попадании", "_приПопадании");
            ОтобразитьСобытие("При промахе", "_приПромахе");
        }
        ОтобразитьСобытие("При перезарядке", "_приПерезарядке");
        ЗакончитьСобытия();
    }
}
#endif
