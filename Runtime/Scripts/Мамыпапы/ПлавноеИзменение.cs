#if UNITY_EDITOR
using UnityEditor;
#endif
using UnityEngine;

/// <summary>
/// Заготовка для Перемещения, Вращения и Масштабирования: плавность, повторы, задержка и события
/// </summary>
public abstract class ПлавноеИзменение : RunityComponent
{
    protected override void OnEnable() { }
    protected override void OnDisable() { }

    [SerializeField] Дробное _длительность = 1;
    /// <summary>
    /// За сколько секунд проходится изменение от начала до конца
    /// </summary>
    public Дробное длительность { get => _длительность; set => _длительность = value; }

    [SerializeField] ВидПлавности _плавность = ВидПлавности.ПлавноСОбеихСторон;
    /// <summary>
    /// Как меняется скорость: равномерно, с плавным стартом, с отскоком в конце и так далее
    /// </summary>
    public ВидПлавности плавность { get => _плавность; set => _плавность = value; }

    [SerializeField] AnimationCurve _своя = AnimationCurve.EaseInOut(0, 0, 1, 1);
    /// <summary>
    /// Своя кривая плавности: слева начало, справа конец. Работает при плавности «Своя кривая»
    /// </summary>
    public AnimationCurve своя { get => _своя; set => _своя = value; }

    [SerializeField] ВидПовтора _повтор = ВидПовтора.ТудаСюда;
    /// <summary>
    /// Что делать в конце: остановиться, начать заново, пойти обратно (туда-сюда) или продолжить с того места, где остановилось
    /// </summary>
    public ВидПовтора повтор { get => _повтор; set => _повтор = value; }

    [SerializeField] Число _сколькоРаз = 0;
    /// <summary>
    /// Сколько раз пройти изменение при повторе. 0 означает, что повторы бесконечны. В режиме «Туда-сюда» путь обратно считается отдельным разом
    /// </summary>
    public Число сколькоРаз { get => _сколькоРаз; set => _сколькоРаз = value; }

    [SerializeField] Дробное _задержка = 0;
    /// <summary>
    /// Сколько секунд подождать перед началом
    /// </summary>
    public Дробное задержка { get => _задержка; set => _задержка = value; }

    [SerializeField] Флажок _запускатьНаСтарте = да;
    /// <summary>
    /// Если "да", то изменение начнётся само при появлении объекта. Иначе его нужно запустить из события или кода
    /// </summary>
    public Флажок запускатьНаСтарте { get => _запускатьНаСтарте; set => _запускатьНаСтарте = value; }

    [SerializeField] События _приНачале;
    /// <summary>
    /// Срабатывает, когда изменение запустилось
    /// </summary>
    public События приНачале => _приНачале;

    [SerializeField] События _приПовторе;
    /// <summary>
    /// Срабатывает каждый раз, когда изменение дошло до конца и пошло на новый круг
    /// </summary>
    public События приПовторе => _приПовторе;

    [SerializeField] События _приЗавершении;
    /// <summary>
    /// Срабатывает, когда все повторы закончились
    /// </summary>
    public События приЗавершении => _приЗавершении;

    /// <summary>
    /// Даёт "да", пока изменение идёт
    /// </summary>
    public Флажок идёт { get; private set; }

    /// <summary>
    /// Пока "да", изменение замерло на месте
    /// </summary>
    public Флажок пауза { get; set; }

    /// <summary>
    /// Сколько раз изменение уже дошло до конца
    /// </summary>
    public Число пройдено { get; private set; }

    float время;
    bool назад;
    bool началоЗапомнено;

    /// <summary>
    /// Запоминает, с чего начинать: текущую позицию, поворот или размер
    /// </summary>
    protected abstract void ЗапомнитьНачало();

    /// <summary>
    /// Ставит объект в состояние между началом (0) и концом (1)
    /// </summary>
    protected abstract void Применить(float доля);

    /// <summary>
    /// Для повтора «Продолжать»: конец становится новым началом
    /// </summary>
    protected abstract void ПеренестиНачалоВКонец();

    /// <summary>
    /// Изменение с постоянной скоростью вместо пути от начала до конца. Так работает постоянное вращение
    /// </summary>
    protected virtual bool бесконечное => false;

    /// <summary>
    /// Шаг бесконечного изменения за кадр
    /// </summary>
    protected virtual void ШагБесконечного(float секунд) { }

    protected virtual void Start()
    {
        if (запускатьНаСтарте) Запустить();
    }

    /// <summary>
    /// Запускает изменение с самого начала
    /// </summary>
    public void Запустить()
    {
        if (!началоЗапомнено) ЗапомнитьНачало();
        началоЗапомнено = true;

        время = -(float)задержка;
        назад = false;
        пройдено = 0;
        пауза = нет;
        идёт = да;
        _приНачале.Вызвать();
    }

    /// <summary>
    /// Останавливает изменение там, где оно сейчас
    /// </summary>
    public void Остановить() => идёт = нет;

    /// <summary>
    /// Ставит изменение на паузу
    /// </summary>
    public void Приостановить() => пауза = да;

    /// <summary>
    /// Снимает изменение с паузы
    /// </summary>
    public void Продолжить() => пауза = нет;

    /// <summary>
    /// Останавливает изменение и возвращает объект в начальное состояние
    /// </summary>
    public void ВернутьВНачало()
    {
        идёт = нет;
        if (началоЗапомнено) Применить(0);
    }

    /// <summary>
    /// Забывает старое начало: следующий запуск начнётся с того, как объект выглядит сейчас
    /// </summary>
    public void НачатьОтсюда()
    {
        ЗапомнитьНачало();
        началоЗапомнено = true;
    }

    protected virtual void Update()
    {
        if (!идёт || пауза) return;

        время += Время.времяСПрошлогоКадра;
        if (время < 0) return;

        if (бесконечное)
        {
            ШагБесконечного(Время.времяСПрошлогоКадра);
            return;
        }

        float секундНаКруг = длительность;
        float доля = секундНаКруг > 0 ? Mathf.Clamp01(время / секундНаКруг) : 1;
        Применить(Плавность.Применить(плавность, назад ? 1 - доля : доля, своя));
        if (доля < 1) return;

        пройдено = (int)пройдено + 1;
        if (повтор == ВидПовтора.НеПовторять || (int)сколькоРаз > 0 && (int)пройдено >= (int)сколькоРаз)
        {
            идёт = нет;
            _приЗавершении.Вызвать();
            return;
        }

        время = секундНаКруг > 0 ? время - секундНаКруг : 0;
        if (повтор == ВидПовтора.ТудаСюда) назад = !назад;
        else if (повтор == ВидПовтора.Продолжать) ПеренестиНачалоВКонец();
        _приПовторе.Вызвать();
    }
}

#if UNITY_EDITOR
internal abstract class ПлавноеИзменениеEditor<T> : RunityEditor<T> where T : ПлавноеИзменение
{
    protected void ОбщиеНастройки()
    {
        Поле("Длительность", x => x.длительность,
            (title, value) => EditorGUILayout.FloatField(title, value));

        Поле("Плавность", x => x.плавность,
            (title, value) => (ВидПлавности)EditorGUILayout.EnumPopup(title, value));

        if (компонент.плавность == ВидПлавности.СвояКривая)
        {
            Поле("Своя кривая", x => x.своя,
                (title, value) => EditorGUILayout.CurveField(title, value));
        }

        Поле("Повтор", x => x.повтор,
            (title, value) => (ВидПовтора)EditorGUILayout.EnumPopup(title, value));

        if (компонент.повтор != ВидПовтора.НеПовторять)
        {
            Поле("Сколько раз", x => x.сколькоРаз,
                (title, value) => Mathf.Max(0, EditorGUILayout.IntField(title, value)));
        }

        ОбщиеНастройкиЗапуска();
    }

    protected void ОбщиеНастройкиЗапуска()
    {
        Поле("Задержка", x => x.задержка,
            (title, value) => EditorGUILayout.FloatField(title, value));

        Поле("Запускать на старте", x => x.запускатьНаСтарте,
            (title, value) => EditorGUILayout.Toggle(title, value));
    }

    protected void ОбщиеСобытия()
    {
        НачатьСобытия();
        ОтобразитьСобытие("При начале", "_приНачале");
        ОтобразитьСобытие("При повторе", "_приПовторе");
        ОтобразитьСобытие("При завершении", "_приЗавершении");
        ЗакончитьСобытия();
    }

    protected void КнопкиЗапуска()
    {
        if (!Application.isPlaying) return;

        НачатьГоризонтальнуюГруппу();
        Кнопка("Запустить", x => x.Запустить());
        Кнопка("Остановить", x => x.Остановить());
        Кнопка("Вернуть в начало", x => x.ВернутьВНачало());
        ЗакончитьГоризонтальнуюГруппу();
    }
}
#endif
