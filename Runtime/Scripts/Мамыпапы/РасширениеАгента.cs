using UnityEngine;

/// <summary>
/// Заготовка для компонентов, которые ставятся рядом с Навигационным агентом и решают, куда ему идти
/// </summary>
[RequireComponent(typeof(НавигационныйАгент))]
public abstract class РасширениеАгента : RunityComponent
{
    НавигационныйАгент _агент;
    /// <summary>
    /// Навигационный агент, которым управляет это расширение
    /// </summary>
    public НавигационныйАгент агент => _агент != null ? _агент : _агент = GetComponent<НавигационныйАгент>();
}
