    /// <summary>
    /// Рисует клавиатуру и мышь целиком. Нажатие на клавишу выбирает её
    /// </summary>
    public static Клавиша Клавиатура(Клавиша выбранная)
    {
        if (стильКлавиши == null)
        {
            стильКлавиши = new GUIStyle(EditorStyles.miniButton) { fontSize = 9, alignment = TextAnchor.MiddleCenter, wordWrap = false, padding = new RectOffset(1, 1, 1, 1) };
            стильКлавиши.fixedHeight = 0;
        }

        const float единицВШирину = 18.75f;
        float ширина = Mathf.Max(200, EditorGUIUtility.currentViewWidth - 40);
        float единица = ширина / единицВШирину;
        float высота = Mathf.Clamp(единица * 1.1f, 18, 32);

        Rect область = GUILayoutUtility.GetRect(ширина, высота * (основнойБлок.Length + 1) + 8);
        область.width = ширина;

        Клавиша результат = выбранная;

        for (int ряд = 0; ряд < основнойБлок.Length; ряд++)
        {
            float y = область.y + ряд * высота + (ряд > 0 ? 4 : 0);
            результат = НарисоватьРяд(основнойБлок[ряд], область.x, y, единица, высота, результат);
            результат = НарисоватьРяд(блокСтрелок[ряд], область.x + единица * 15.75f, y, единица, высота, результат);
        }

        float yМыши = область.y + основнойБлок.Length * высота + 8;
        результат = НарисоватьРяд(мышь, область.x, yМыши, единица, высота, результат);

        return результат;
    }

    static Клавиша НарисоватьРяд(Кнопка[] ряд, float x, float y, float единица, float высота, Клавиша выбранная)
    {
        Клавиша результат = выбранная;

        foreach (Кнопка кнопка in ряд)
        {
            float ширинаКнопки = кнопка.ширина * единица;

            if (кнопка.клавиша.HasValue)
            {
                Клавиша клавиша = кнопка.клавиша.Value;
                Rect место = new Rect(x + 1, y + 1, ширинаКнопки - 2, высота - 2);

                Color было = GUI.backgroundColor;
                if (клавиша == выбранная)
                {
                    GUI.backgroundColor = Application.isPlaying && Управление.КлавишаУдерживается(клавиша) ? цветНажатой : цветВыбранной;
                }

                if (GUI.Button(место, new GUIContent(кнопка.надпись, клавиша.ToString()), стильКлавиши)) результат = клавиша;

                GUI.backgroundColor = было;
            }

            x += ширинаКнопки;
        }

        return результат;
    }

    static readonly Dictionary<string, bool> открытые = new Dictionary<string, bool>();

    /// <summary>
    /// Короткое поле: выбранная клавиша и кнопка, которая раскрывает клавиатуру
    /// </summary>
    public static Клавиша Поле(GUIContent подпись, Клавиша выбранная, string ключ)
    {
        открытые.TryGetValue(ключ, out bool открыта);

        EditorGUILayout.BeginHorizontal();
        EditorGUILayout.PrefixLabel(подпись);
        if (GUILayout.Button(new GUIContent($"{выбранная}  ▾", подпись.tooltip), EditorStyles.popup))
        {
            открыта = !открыта;
            открытые[ключ] = открыта;
        }
        EditorGUILayout.EndHorizontal();

        return открыта ? Клавиатура(выбранная) : выбранная;
    }
