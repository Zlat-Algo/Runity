using UnityEngine;

/// <summary>
/// Как меняется скорость во время плавного движения
/// </summary>
public enum ВидПлавности { Равномерно, ПлавныйСтарт, ПлавнаяОстановка, ПлавноСОбеихСторон, СПружинкой, СЗамахом, СОтскоком, Резинка, СильныйРазгон, СильноеТорможение, Волной, СвояКривая }

/// <summary>
/// Что происходит, когда плавное изменение доходит до конца
/// </summary>
public enum ВидПовтора { НеПовторять, Заново, ТудаСюда, Продолжать }

/// <summary>
/// Формулы плавности. Превращают долю пройденного времени (от 0 до 1) в долю пройденного пути
/// </summary>
public static class Плавность
{
    const float замах = 1.70158f;

    /// <summary>
    /// Даёт долю пути для указанной доли времени. Своя кривая нужна только для вида «Своя кривая»
    /// </summary>
    public static Дробное Применить(ВидПлавности вид, Дробное доляВремени, AnimationCurve своя = null)
    {
        float t = Mathf.Clamp01(доляВремени);
        switch (вид)
        {
            case ВидПлавности.ПлавныйСтарт: return t * t;
            case ВидПлавности.ПлавнаяОстановка: return 1 - (1 - t) * (1 - t);
            case ВидПлавности.ПлавноСОбеихСторон: return t * t * (3 - 2 * t);
            case ВидПлавности.СПружинкой: return 1 + (замах + 1) * Mathf.Pow(t - 1, 3) + замах * Mathf.Pow(t - 1, 2);
            case ВидПлавности.СЗамахом: return (замах + 1) * t * t * t - замах * t * t;
            case ВидПлавности.СОтскоком: return Отскок(t);
            case ВидПлавности.Резинка:
                if (t <= 0 || t >= 1) return t;
                return Mathf.Pow(2, -10 * t) * Mathf.Sin((t * 10 - 0.75f) * (2 * Mathf.PI / 3)) + 1;
            case ВидПлавности.СильныйРазгон: return t <= 0 ? 0 : Mathf.Pow(2, 10 * t - 10);
            case ВидПлавности.СильноеТорможение: return t >= 1 ? 1 : 1 - Mathf.Pow(2, -10 * t);
            case ВидПлавности.Волной: return -(Mathf.Cos(Mathf.PI * t) - 1) / 2;
            case ВидПлавности.СвояКривая: return своя != null && своя.length > 0 ? своя.Evaluate(t) : t;
            default: return t;
        }
    }

    static float Отскок(float t)
    {
        const float n = 7.5625f, d = 2.75f;
        if (t < 1 / d) return n * t * t;
        if (t < 2 / d) { t -= 1.5f / d; return n * t * t + 0.75f; }
        if (t < 2.5f / d) { t -= 2.25f / d; return n * t * t + 0.9375f; }
        t -= 2.625f / d;
        return n * t * t + 0.984375f;
    }
}
