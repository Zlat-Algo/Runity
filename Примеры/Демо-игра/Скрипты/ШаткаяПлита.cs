using UnityEngine;

/// <summary>
/// Плита, которая проваливается, если на ней задержаться. Сначала мигает, потом падает и через время возвращается.
/// Нужны компоненты: Касание (зона над плитой), Перемещение (как падать) и Мигание (предупреждение)
/// </summary>
public class ШаткаяПлита : Компонент
{
    [Подсказка("Зона над плитой, которая замечает игрока")]
    [Обязательное] public Касание касание;

    [Подсказка("Сколько секунд можно стоять на плите, пока она не упала")]
    public float терпение = 0.8f;

    [Подсказка("Через сколько секунд упавшая плита возвращается")]
    public float возвращение = 3;

    Перемещение падение;
    Мигание мигание;
    bool ждёт, упала;

    void Awake()
    {
        падение = GetComponent<Перемещение>();
        мигание = GetComponent<Мигание>();
    }

    void Update()
    {
        if (упала || ждёт || !касание.внутри) return;

        ждёт = true;
        if (мигание != null) мигание.Мигнуть(терпение);
        // Плита упадёт, только ЕСЛИ игрок через это время всё ещё стоит на ней
        ВызватьСЗадержкойЕсли(Упасть, () => касание.внутри, терпение);
        ВызватьСЗадержкой(() => ждёт = false, терпение + 0.05f);
    }

    void Упасть()
    {
        упала = true;
        падение.Запустить();
        ВызватьСЗадержкой(Вернуться, возвращение);
    }

    void Вернуться()
    {
        падение.ВернутьВНачало();
        упала = false;
    }
}
